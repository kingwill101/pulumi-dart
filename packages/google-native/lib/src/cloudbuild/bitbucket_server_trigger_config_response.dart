// ignore_for_file: unused_element, unnecessary_cast

import 'bitbucket_server_config_response.dart';
import 'pull_request_filter_response.dart';
import 'push_filter_response.dart';

/// BitbucketServerTriggerConfig describes the configuration of a trigger that creates a build whenever a Bitbucket Server event is received.
class BitbucketServerTriggerConfigResponse {
  /// The BitbucketServerConfig specified in the bitbucket_server_config_resource field.
  final BitbucketServerConfigResponse bitbucketServerConfig;

  /// The Bitbucket server config resource that this trigger config maps to.
  final String bitbucketServerConfigResource;

  /// Key of the project that the repo is in. For example: The key for https://mybitbucket.server/projects/TEST/repos/test-repo is "TEST".
  final String projectKey;

  /// Filter to match changes in pull requests.
  final PullRequestFilterResponse pullRequest;

  /// Filter to match changes in refs like branches, tags.
  final PushFilterResponse push;

  /// Slug of the repository. A repository slug is a URL-friendly version of a repository name, automatically generated by Bitbucket for use in the URL. For example, if the repository name is 'test repo', in the URL it would become 'test-repo' as in https://mybitbucket.server/projects/TEST/repos/test-repo.
  final String repoSlug;

  /// Creates a new [BitbucketServerTriggerConfigResponse].
  /// [bitbucketServerConfig] The BitbucketServerConfig specified in the bitbucket_server_config_resource field.
  /// [bitbucketServerConfigResource] The Bitbucket server config resource that this trigger config maps to.
  /// [projectKey] Key of the project that the repo is in. For example: The key for https://mybitbucket.server/projects/TEST/repos/test-repo is "TEST".
  /// [pullRequest] Filter to match changes in pull requests.
  /// [push] Filter to match changes in refs like branches, tags.
  /// [repoSlug] Slug of the repository. A repository slug is a URL-friendly version of a repository name, automatically generated by Bitbucket for use in the URL. For example, if the repository name is 'test repo', in the URL it would become 'test-repo' as in https://mybitbucket.server/projects/TEST/repos/test-repo.
  BitbucketServerTriggerConfigResponse({
    required this.bitbucketServerConfig,
    required this.bitbucketServerConfigResource,
    required this.projectKey,
    required this.pullRequest,
    required this.push,
    required this.repoSlug,
  });

  Map<String, dynamic> toMap() {
    final map = <String, dynamic>{};
    map['bitbucketServerConfig'] = bitbucketServerConfig.toMap();
    map['bitbucketServerConfigResource'] = bitbucketServerConfigResource;
    map['projectKey'] = projectKey;
    map['pullRequest'] = pullRequest.toMap();
    map['push'] = push.toMap();
    map['repoSlug'] = repoSlug;
    return map;
  }

  factory BitbucketServerTriggerConfigResponse.fromMap(
      Map<String, dynamic> map) {
    return BitbucketServerTriggerConfigResponse(
      bitbucketServerConfig: BitbucketServerConfigResponse.fromMap(
          (map['bitbucketServerConfig'] as Map).cast<String, dynamic>()),
      bitbucketServerConfigResource:
          map['bitbucketServerConfigResource'] as String,
      projectKey: map['projectKey'] as String,
      pullRequest: PullRequestFilterResponse.fromMap(
          (map['pullRequest'] as Map).cast<String, dynamic>()),
      push: PushFilterResponse.fromMap(
          (map['push'] as Map).cast<String, dynamic>()),
      repoSlug: map['repoSlug'] as String,
    );
  }
}
