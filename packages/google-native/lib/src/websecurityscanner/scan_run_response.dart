    final map = <String, dynamic>{};
    map['endTime'] = endTime;
    map['executionState'] = executionState;
    map['hasVulnerabilities'] = hasVulnerabilities;
    map['name'] = name;
    map['progressPercent'] = progressPercent;
    map['resultState'] = resultState;
    map['startTime'] = startTime;
    map['urlsCrawledCount'] = urlsCrawledCount;
    map['urlsTestedCount'] = urlsTestedCount;
    return map;
  }

  factory ScanRunResponse.fromMap(Map<String, dynamic> map) {
    return ScanRunResponse(
      endTime: map['endTime'] as String,
      executionState: map['executionState'] as String,
      hasVulnerabilities: map['hasVulnerabilities'] as bool,
      name: map['name'] as String,
      progressPercent: map['progressPercent'] as int,
      resultState: map['resultState'] as String,
      startTime: map['startTime'] as String,
      urlsCrawledCount: map['urlsCrawledCount'] as String,
      urlsTestedCount: map['urlsTestedCount'] as String,
    );
  }
}
