import 'package:pulumi/pulumi.dart';
import 'google_cloud_apigee_v1_profile_config_response.dart';
import 'google_cloud_apigee_v1_security_profile_environment_response.dart';
import 'google_cloud_apigee_v1_security_profile_scoring_config_response.dart';
import 'security_profile_args.dart';

/// CreateSecurityProfile create a new custom security profile.
class SecurityProfile extends CustomResource {
  /// Description of the security profile.
  late final Output<String> description;

  /// Display name of the security profile.
  late final Output<String> displayName;

  /// List of environments attached to security profile.
  late final Output<List<GoogleCloudApigeeV1SecurityProfileEnvironmentResponse>>
      environments;

  /// Maximum security score that can be generated by this profile.
  late final Output<int> maxScore;

  /// Minimum security score that can be generated by this profile.
  late final Output<int> minScore;

  /// Immutable. Name of the security profile resource. Format: organizations/{org}/securityProfiles/{profile}
  late final Output<String> name;
  late final Output<String> organizationId;

  /// Customized profile configuration that computes the security score.
  late final Output<GoogleCloudApigeeV1ProfileConfigResponse> profileConfig;

  /// The time when revision was created.
  late final Output<String> revisionCreateTime;

  /// Revision ID of the security profile.
  late final Output<String> revisionId;

  /// The time when revision was published. Once published, the security profile revision cannot be updated further and can be attached to environments.
  late final Output<String> revisionPublishTime;

  /// The time when revision was updated.
  late final Output<String> revisionUpdateTime;

  /// List of profile scoring configs in this revision.
  late final Output<
          List<GoogleCloudApigeeV1SecurityProfileScoringConfigResponse>>
      scoringConfigs;

  /// Required. The ID to use for the SecurityProfile, which will become the final component of the action's resource name. This value should be 1-63 characters and validated by "(^[a-z]([a-z0-9-]{0,61}[a-z0-9])?$)".
  late final Output<String> securityProfileId;

  SecurityProfile(
    String name, {
    SecurityProfileArgs? args,
    CustomResourceOptions? options,
  }) : super(
          'google-native:apigee/v1:SecurityProfile',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.description = Output.createUnknown<String>();
    this.displayName = Output.createUnknown<String>();
    this.environments = Output.createUnknown<
        List<GoogleCloudApigeeV1SecurityProfileEnvironmentResponse>>();
    this.maxScore = Output.createUnknown<int>();
    this.minScore = Output.createUnknown<int>();
    this.name = Output.createUnknown<String>();
    this.organizationId = Output.createUnknown<String>();
    this.profileConfig =
        Output.createUnknown<GoogleCloudApigeeV1ProfileConfigResponse>();
    this.revisionCreateTime = Output.createUnknown<String>();
    this.revisionId = Output.createUnknown<String>();
    this.revisionPublishTime = Output.createUnknown<String>();
    this.revisionUpdateTime = Output.createUnknown<String>();
    this.scoringConfigs = Output.createUnknown<
        List<GoogleCloudApigeeV1SecurityProfileScoringConfigResponse>>();
    this.securityProfileId = Output.createUnknown<String>();
  }
}
