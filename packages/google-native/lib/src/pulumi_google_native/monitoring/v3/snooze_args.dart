    final map = <String, dynamic>{};
    map['criteria'] =
        pulumi.Input.mapInputValue<Criteria, Map<String, dynamic>>(
            criteria, (value) => value.toMap());
    map['displayName'] = displayName;
    map['interval'] =
        pulumi.Input.mapInputValue<TimeInterval, Map<String, dynamic>>(
            interval, (value) => value.toMap());
