// ignore_for_file: unused_element, unnecessary_cast

import 'authentication_response2.dart';
import 'schedule_response3.dart';

/// Result data returned by getScanConfig.
class GetScanConfigResult {
  /// The authentication configuration. If specified, service will use the authentication configuration during scanning.
  final AuthenticationResponse2 authentication;

  /// The excluded URL patterns as described in https://cloud.google.com/security-command-center/docs/how-to-use-web-security-scanner#excluding_urls
  final List<String> blacklistPatterns;

  /// The user provided display name of the ScanConfig.
  final String displayName;

  /// Controls export of scan configurations and results to Security Command Center.
  final String exportToSecurityCommandCenter;

  /// Whether to keep scanning even if most requests return HTTP error codes.
  final bool ignoreHttpStatusErrors;

  /// Whether the scan config is managed by Web Security Scanner, output only.
  final bool managedScan;

  /// The maximum QPS during scanning. A valid value ranges from 5 to 20 inclusively. If the field is unspecified or its value is set 0, server will default to 15. Other values outside of [5, 20] range will be rejected with INVALID_ARGUMENT error.
  final int maxQps;

  /// The resource name of the ScanConfig. The name follows the format of 'projects/{projectId}/scanConfigs/{scanConfigId}'. The ScanConfig IDs are generated by the system.
  final String name;

  /// The risk level selected for the scan
  final String riskLevel;

  /// The schedule of the ScanConfig.
  final ScheduleResponse3 schedule;

  /// The starting URLs from which the scanner finds site pages.
  final List<String> startingUrls;

  /// Whether the scan configuration has enabled static IP address scan feature. If enabled, the scanner will access applications from static IP addresses.
  final bool staticIpScan;

  /// The user agent used during scanning.
  final String userAgent;

  GetScanConfigResult({
    required this.authentication,
    required this.blacklistPatterns,
    required this.displayName,
    required this.exportToSecurityCommandCenter,
    required this.ignoreHttpStatusErrors,
    required this.managedScan,
    required this.maxQps,
    required this.name,
    required this.riskLevel,
    required this.schedule,
    required this.startingUrls,
    required this.staticIpScan,
    required this.userAgent,
  });

  Map<String, dynamic> toMap() {
    final map = <String, dynamic>{};
    map['authentication'] = authentication.toMap();
    map['blacklistPatterns'] = blacklistPatterns;
    map['displayName'] = displayName;
    map['exportToSecurityCommandCenter'] = exportToSecurityCommandCenter;
    map['ignoreHttpStatusErrors'] = ignoreHttpStatusErrors;
    map['managedScan'] = managedScan;
    map['maxQps'] = maxQps;
    map['name'] = name;
    map['riskLevel'] = riskLevel;
    map['schedule'] = schedule.toMap();
    map['startingUrls'] = startingUrls;
    map['staticIpScan'] = staticIpScan;
    map['userAgent'] = userAgent;
    return map;
  }

  factory GetScanConfigResult.fromMap(Map<String, dynamic> map) {
    return GetScanConfigResult(
      authentication: AuthenticationResponse2.fromMap(
          (map['authentication'] as Map).cast<String, dynamic>()),
      blacklistPatterns: (map['blacklistPatterns'] as List).cast<String>(),
      displayName: map['displayName'] as String,
      exportToSecurityCommandCenter:
          map['exportToSecurityCommandCenter'] as String,
      ignoreHttpStatusErrors: map['ignoreHttpStatusErrors'] as bool,
      managedScan: map['managedScan'] as bool,
      maxQps: map['maxQps'] as int,
      name: map['name'] as String,
      riskLevel: map['riskLevel'] as String,
      schedule: ScheduleResponse3.fromMap(
          (map['schedule'] as Map).cast<String, dynamic>()),
      startingUrls: (map['startingUrls'] as List).cast<String>(),
      staticIpScan: map['staticIpScan'] as bool,
      userAgent: map['userAgent'] as String,
    );
  }
}
