import 'package:pulumi/pulumi.dart';
import 'authentication_response3.dart';
import 'scan_config_args2.dart';
import 'scan_run_response.dart';
import 'schedule_response4.dart';

/// Creates a new ScanConfig.
class ScanConfig2 extends CustomResource {
  /// The authentication configuration. If specified, service will use the authentication configuration during scanning.
  late final Output<AuthenticationResponse3> authentication;

  /// The excluded URL patterns as described in https://cloud.google.com/security-command-center/docs/how-to-use-web-security-scanner#excluding_urls
  late final Output<List<String>> blacklistPatterns;

  /// The user provided display name of the ScanConfig.
  late final Output<String> displayName;

  /// Latest ScanRun if available.
  late final Output<ScanRunResponse> latestRun;

  /// The maximum QPS during scanning. A valid value ranges from 5 to 20 inclusively. If the field is unspecified or its value is set 0, server will default to 15. Other values outside of [5, 20] range will be rejected with INVALID_ARGUMENT error.
  late final Output<int> maxQps;

  /// The resource name of the ScanConfig. The name follows the format of 'projects/{projectId}/scanConfigs/{scanConfigId}'. The ScanConfig IDs are generated by the system.
  late final Output<String> name;
  late final Output<String> project;

  /// The schedule of the ScanConfig.
  late final Output<ScheduleResponse4> schedule;

  /// The starting URLs from which the scanner finds site pages.
  late final Output<List<String>> startingUrls;

  /// Set of Google Cloud platforms targeted by the scan. If empty, APP_ENGINE will be used as a default.
  late final Output<List<String>> targetPlatforms;

  /// The user agent used during scanning.
  late final Output<String> userAgent;

  ScanConfig2(
    String name, {
    ScanConfigArgs2? args,
    CustomResourceOptions? options,
  }) : super(
          'google-native:websecurityscanner/v1alpha:ScanConfig',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.authentication =
        registerOutput<AuthenticationResponse3>('authentication');
    this.blacklistPatterns = registerOutput<List<String>>('blacklistPatterns');
    this.displayName = registerOutput<String>('displayName');
    this.latestRun = registerOutput<ScanRunResponse>('latestRun');
    this.maxQps = registerOutput<int>('maxQps');
    this.name = registerOutput<String>('name');
    this.project = registerOutput<String>('project');
    this.schedule = registerOutput<ScheduleResponse4>('schedule');
    this.startingUrls = registerOutput<List<String>>('startingUrls');
    this.targetPlatforms = registerOutput<List<String>>('targetPlatforms');
    this.userAgent = registerOutput<String>('userAgent');
  }
}
