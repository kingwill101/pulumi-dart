// ignore_for_file: unused_element, unnecessary_cast

import 'scan_run_execution_state.dart';
import 'scan_run_result_state.dart';

/// A ScanRun is a output-only resource representing an actual run of the scan.
class ScanRun {
  /// The time at which the ScanRun reached termination state - that the ScanRun is either finished or stopped by user.
  final String? endTime;

  /// The execution state of the ScanRun.
  final ScanRunExecutionState? executionState;

  /// Whether the scan run has found any vulnerabilities.
  final bool? hasVulnerabilities;

  /// The resource name of the ScanRun. The name follows the format of 'projects/{projectId}/scanConfigs/{scanConfigId}/scanRuns/{scanRunId}'. The ScanRun IDs are generated by the system.
  final String? name;

  /// The percentage of total completion ranging from 0 to 100. If the scan is in queue, the value is 0. If the scan is running, the value ranges from 0 to 100. If the scan is finished, the value is 100.
  final int? progressPercent;

  /// The result state of the ScanRun. This field is only available after the execution state reaches "FINISHED".
  final ScanRunResultState? resultState;

  /// The time at which the ScanRun started.
  final String? startTime;

  /// The number of URLs crawled during this ScanRun. If the scan is in progress, the value represents the number of URLs crawled up to now.
  final String? urlsCrawledCount;

  /// The number of URLs tested during this ScanRun. If the scan is in progress, the value represents the number of URLs tested up to now. The number of URLs tested is usually larger than the number URLS crawled because typically a crawled URL is tested with multiple test payloads.
  final String? urlsTestedCount;

  ScanRun({
    this.endTime,
    this.executionState,
    this.hasVulnerabilities,
    this.name,
    this.progressPercent,
    this.resultState,
    this.startTime,
    this.urlsCrawledCount,
    this.urlsTestedCount,
  });

  Map<String, dynamic> toMap() {
    final map = <String, dynamic>{};
    final endTimeValue = endTime;
    if (endTimeValue != null) {
      map['endTime'] = endTimeValue;
    }
    final executionStateValue = executionState;
    if (executionStateValue != null) {
      map['executionState'] = executionStateValue.value;
    }
    final hasVulnerabilitiesValue = hasVulnerabilities;
    if (hasVulnerabilitiesValue != null) {
      map['hasVulnerabilities'] = hasVulnerabilitiesValue;
    }
    final nameValue = name;
    if (nameValue != null) {
      map['name'] = nameValue;
    }
    final progressPercentValue = progressPercent;
    if (progressPercentValue != null) {
      map['progressPercent'] = progressPercentValue;
    }
    final resultStateValue = resultState;
    if (resultStateValue != null) {
      map['resultState'] = resultStateValue.value;
    }
    final startTimeValue = startTime;
    if (startTimeValue != null) {
      map['startTime'] = startTimeValue;
    }
    final urlsCrawledCountValue = urlsCrawledCount;
    if (urlsCrawledCountValue != null) {
      map['urlsCrawledCount'] = urlsCrawledCountValue;
    }
    final urlsTestedCountValue = urlsTestedCount;
    if (urlsTestedCountValue != null) {
      map['urlsTestedCount'] = urlsTestedCountValue;
    }
    return map;
  }

  factory ScanRun.fromMap(Map<String, dynamic> map) {
    return ScanRun(
      endTime: map['endTime'] == null ? null : map['endTime'] as String,
      executionState: map['executionState'] == null
          ? null
          : ScanRunExecutionState.fromValue(map['executionState'] as String),
      hasVulnerabilities: map['hasVulnerabilities'] == null
          ? null
          : map['hasVulnerabilities'] as bool,
      name: map['name'] == null ? null : map['name'] as String,
      progressPercent:
          map['progressPercent'] == null ? null : map['progressPercent'] as int,
      resultState: map['resultState'] == null
          ? null
          : ScanRunResultState.fromValue(map['resultState'] as String),
      startTime: map['startTime'] == null ? null : map['startTime'] as String,
      urlsCrawledCount: map['urlsCrawledCount'] == null
          ? null
          : map['urlsCrawledCount'] as String,
      urlsTestedCount: map['urlsTestedCount'] == null
          ? null
          : map['urlsTestedCount'] as String,
    );
  }
}
