import 'package:pulumi/pulumi.dart';
import 'artifacts_response.dart';
import 'build_approval_response.dart';
import 'build_args.dart';
import 'build_options_response.dart';
import 'build_step_response.dart';
import 'failure_info_response.dart';
import 'results_response.dart';
import 'secret_response.dart';
import 'secrets_response.dart';
import 'source_provenance_response.dart';
import 'source_response.dart';
import 'warning_response.dart';

/// Starts a build with the specified configuration. This method returns a long-running `Operation`, which includes the build ID. Pass the build ID to `GetBuild` to determine the build status (such as `SUCCESS` or `FAILURE`).
/// Auto-naming is currently not supported for this resource.
/// Note - this resource's API doesn't support deletion. When deleted, the resource will persist
/// on Google Cloud even though it will be deleted from Pulumi state.
class Build3 extends CustomResource {
  /// Describes this build's approval configuration, status, and result.
  late final Output<BuildApprovalResponse> approval;

  /// Artifacts produced by the build that should be uploaded upon successful completion of all build steps.
  late final Output<ArtifactsResponse> artifacts;

  /// Secrets and secret environment variables.
  late final Output<SecretsResponse> availableSecrets;

  /// The ID of the `BuildTrigger` that triggered this build, if it was triggered automatically.
  late final Output<String> buildTriggerId;

  /// Time at which the request to create the build was received.
  late final Output<String> createTime;

  /// Contains information about the build when status=FAILURE.
  late final Output<FailureInfoResponse> failureInfo;

  /// Time at which execution of the build was finished. The difference between finish_time and start_time is the duration of the build's execution.
  late final Output<String> finishTime;

  /// A list of images to be pushed upon the successful completion of all build steps. The images are pushed using the builder service account's credentials. The digests of the pushed images will be stored in the `Build` resource's results field. If any of the images fail to be pushed, the build status is marked `FAILURE`.
  late final Output<List<String>> images;
  late final Output<String> location;

  /// URL to logs for this build in Google Cloud Console.
  late final Output<String> logUrl;

  /// Cloud Storage bucket where logs should be written (see [Bucket Name Requirements](https://cloud.google.com/storage/docs/bucket-naming#requirements)). Logs file names will be of the format `${logs_bucket}/log-${build_id}.txt`.
  late final Output<String> logsBucket;

  /// The 'Build' name with format: `projects/{project}/locations/{location}/builds/{build}`, where {build} is a unique identifier generated by the service.
  late final Output<String> name;

  /// Special options for this build.
  late final Output<BuildOptionsResponse> options;
  late final Output<String> project;

  /// Required. ID of the project.
  late final Output<String> projectId;

  /// TTL in queue for this build. If provided and the build is enqueued longer than this value, the build will expire and the build status will be `EXPIRED`. The TTL starts ticking from create_time.
  late final Output<String> queueTtl;

  /// Results of the build.
  late final Output<ResultsResponse> results;

  /// Secrets to decrypt using Cloud Key Management Service. Note: Secret Manager is the recommended technique for managing sensitive data with Cloud Build. Use `available_secrets` to configure builds to access secrets from Secret Manager. For instructions, see: https://cloud.google.com/cloud-build/docs/securing-builds/use-secrets
  late final Output<List<SecretResponse>> secrets;

  /// IAM service account whose credentials will be used at build runtime. Must be of the format `projects/{PROJECT_ID}/serviceAccounts/{ACCOUNT}`. ACCOUNT can be email address or uniqueId of the service account.
  late final Output<String> serviceAccount;

  /// The location of the source files to build.
  late final Output<SourceResponse> source;

  /// A permanent fixed identifier for source.
  late final Output<SourceProvenanceResponse> sourceProvenance;

  /// Time at which execution of the build was started.
  late final Output<String> startTime;

  /// Status of the build.
  late final Output<String> status;

  /// Customer-readable message about the current status.
  late final Output<String> statusDetail;

  /// The operations to be performed on the workspace.
  late final Output<List<BuildStepResponse>> steps;

  /// Substitutions data for `Build` resource.
  late final Output<Map<String, String>> substitutions;

  /// Tags for annotation of a `Build`. These are not docker tags.
  late final Output<List<String>> tags;

  /// Amount of time that this build should be allowed to run, to second granularity. If this amount of time elapses, work on the build will cease and the build status will be `TIMEOUT`. `timeout` starts ticking from `startTime`. Default time is 60 minutes.
  late final Output<String> timeout;

  /// Stores timing information for phases of the build. Valid keys are: * BUILD: time to execute all build steps. * PUSH: time to push all artifacts including docker images and non docker artifacts. * FETCHSOURCE: time to fetch source. * SETUPBUILD: time to set up build. If the build does not specify source or images, these keys will not be included.
  late final Output<Map<String, String>> timing;

  /// Non-fatal problems encountered during the execution of the build.
  late final Output<List<WarningResponse>> warnings;

  Build3(
    String name, {
    BuildArgs? args,
    CustomResourceOptions? options,
  }) : super(
          'google-native:cloudbuild/v1:Build',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.approval = Output.createUnknown<BuildApprovalResponse>();
    this.artifacts = Output.createUnknown<ArtifactsResponse>();
    this.availableSecrets = Output.createUnknown<SecretsResponse>();
    this.buildTriggerId = Output.createUnknown<String>();
    this.createTime = Output.createUnknown<String>();
    this.failureInfo = Output.createUnknown<FailureInfoResponse>();
    this.finishTime = Output.createUnknown<String>();
    this.images = Output.createUnknown<List<String>>();
    this.location = Output.createUnknown<String>();
    this.logUrl = Output.createUnknown<String>();
    this.logsBucket = Output.createUnknown<String>();
    this.name = Output.createUnknown<String>();
    this.options = Output.createUnknown<BuildOptionsResponse>();
    this.project = Output.createUnknown<String>();
    this.projectId = Output.createUnknown<String>();
    this.queueTtl = Output.createUnknown<String>();
    this.results = Output.createUnknown<ResultsResponse>();
    this.secrets = Output.createUnknown<List<SecretResponse>>();
    this.serviceAccount = Output.createUnknown<String>();
    this.source = Output.createUnknown<SourceResponse>();
    this.sourceProvenance = Output.createUnknown<SourceProvenanceResponse>();
    this.startTime = Output.createUnknown<String>();
    this.status = Output.createUnknown<String>();
    this.statusDetail = Output.createUnknown<String>();
    this.steps = Output.createUnknown<List<BuildStepResponse>>();
    this.substitutions = Output.createUnknown<Map<String, String>>();
    this.tags = Output.createUnknown<List<String>>();
    this.timeout = Output.createUnknown<String>();
    this.timing = Output.createUnknown<Map<String, String>>();
    this.warnings = Output.createUnknown<List<WarningResponse>>();
  }
}
