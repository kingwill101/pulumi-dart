import 'package:pulumi/pulumi.dart';
import 'approval_config_response.dart';
import 'bitbucket_server_trigger_config_response.dart';
import 'build_response2.dart';
import 'git_file_source_response.dart';
import 'git_hub_events_config_response.dart';
import 'git_lab_events_config_response.dart';
import 'git_repo_source_response.dart';
import 'pubsub_config_response.dart';
import 'repo_source_response.dart';
import 'repository_event_config_response.dart';
import 'trigger_args.dart';
import 'webhook_config_response.dart';

/// Creates a new `BuildTrigger`.
class Trigger2 extends CustomResource {
  /// Configuration for manual approval to start a build invocation of this BuildTrigger.
  late final Output<ApprovalConfigResponse> approvalConfig;

  /// Autodetect build configuration. The following precedence is used (case insensitive): 1. cloudbuild.yaml 2. cloudbuild.yml 3. cloudbuild.json 4. Dockerfile Currently only available for GitHub App Triggers.
  late final Output<bool> autodetect;

  /// BitbucketServerTriggerConfig describes the configuration of a trigger that creates a build whenever a Bitbucket Server event is received.
  late final Output<BitbucketServerTriggerConfigResponse>
      bitbucketServerTriggerConfig;

  /// Contents of the build template.
  late final Output<BuildResponse2> build;

  /// Time when the trigger was created.
  late final Output<String> createTime;

  /// Human-readable description of this trigger.
  late final Output<String> description;

  /// If true, the trigger will never automatically execute a build.
  late final Output<bool> disabled;

  /// EventType allows the user to explicitly set the type of event to which this BuildTrigger should respond. This field will be validated against the rest of the configuration if it is set.
  late final Output<String> eventType;

  /// Path, from the source root, to the build configuration file (i.e. cloudbuild.yaml).
  late final Output<String> filename;

  /// A Common Expression Language string.
  late final Output<String> filter;

  /// The file source describing the local or remote Build template.
  late final Output<GitFileSourceResponse> gitFileSource;

  /// GitHubEventsConfig describes the configuration of a trigger that creates a build whenever a GitHub event is received. Mutually exclusive with `trigger_template`.
  late final Output<GitHubEventsConfigResponse> github;

  /// GitLabEnterpriseEventsConfig describes the configuration of a trigger that creates a build whenever a GitLab Enterprise event is received.
  late final Output<GitLabEventsConfigResponse> gitlabEnterpriseEventsConfig;

  /// ignored_files and included_files are file glob matches using https://golang.org/pkg/path/filepath/#Match extended with support for "**". If ignored_files and changed files are both empty, then they are not used to determine whether or not to trigger a build. If ignored_files is not empty, then we ignore any files that match any of the ignored_file globs. If the change has no files that are outside of the ignored_files globs, then we do not trigger a build.
  late final Output<List<String>> ignoredFiles;

  /// If set to INCLUDE_BUILD_LOGS_WITH_STATUS, log url will be shown on GitHub page when build status is final. Setting this field to INCLUDE_BUILD_LOGS_WITH_STATUS for non GitHub triggers results in INVALID_ARGUMENT error.
  late final Output<String> includeBuildLogs;

  /// If any of the files altered in the commit pass the ignored_files filter and included_files is empty, then as far as this filter is concerned, we should trigger the build. If any of the files altered in the commit pass the ignored_files filter and included_files is not empty, then we make sure that at least one of those files matches a included_files glob. If not, then we do not trigger a build.
  late final Output<List<String>> includedFiles;
  late final Output<String> location;

  /// User-assigned name of the trigger. Must be unique within the project. Trigger names must meet the following requirements: + They must contain only alphanumeric characters and dashes. + They can be 1-64 characters long. + They must begin and end with an alphanumeric character.
  late final Output<String> name;
  late final Output<String> project;

  /// Required. ID of the project for which to configure automatic builds.
  late final Output<String> projectId;

  /// PubsubConfig describes the configuration of a trigger that creates a build whenever a Pub/Sub message is published.
  late final Output<PubsubConfigResponse> pubsubConfig;

  /// The configuration of a trigger that creates a build whenever an event from Repo API is received.
  late final Output<RepositoryEventConfigResponse> repositoryEventConfig;

  /// The `Trigger` name with format: `projects/{project}/locations/{location}/triggers/{trigger}`, where {trigger} is a unique identifier generated by the service.
  late final Output<String> resourceName;

  /// The service account used for all user-controlled operations including UpdateBuildTrigger, RunBuildTrigger, CreateBuild, and CancelBuild. If no service account is set, then the standard Cloud Build service account ([PROJECT_NUM]@system.gserviceaccount.com) will be used instead. Format: `projects/{PROJECT_ID}/serviceAccounts/{ACCOUNT_ID_OR_EMAIL}`
  late final Output<String> serviceAccount;

  /// The repo and ref of the repository from which to build. This field is used only for those triggers that do not respond to SCM events. Triggers that respond to such events build source at whatever commit caused the event. This field is currently only used by Webhook, Pub/Sub, Manual, and Cron triggers.
  late final Output<GitRepoSourceResponse> sourceToBuild;

  /// Substitutions for Build resource. The keys must match the following regular expression: `^_[A-Z0-9_]+$`.
  late final Output<Map<String, String>> substitutions;

  /// Tags for annotation of a `BuildTrigger`
  late final Output<List<String>> tags;

  /// Template describing the types of source changes to trigger a build. Branch and tag names in trigger templates are interpreted as regular expressions. Any branch or tag change that matches that regular expression will trigger a build. Mutually exclusive with `github`.
  late final Output<RepoSourceResponse> triggerTemplate;

  /// WebhookConfig describes the configuration of a trigger that creates a build whenever a webhook is sent to a trigger's webhook URL.
  late final Output<WebhookConfigResponse> webhookConfig;

  Trigger2(
    String name, {
    TriggerArgs? args,
    CustomResourceOptions? options,
  }) : super(
          'google-native:cloudbuild/v1:Trigger',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.approvalConfig = Output.createUnknown<ApprovalConfigResponse>();
    this.autodetect = Output.createUnknown<bool>();
    this.bitbucketServerTriggerConfig =
        Output.createUnknown<BitbucketServerTriggerConfigResponse>();
    this.build = Output.createUnknown<BuildResponse2>();
    this.createTime = Output.createUnknown<String>();
    this.description = Output.createUnknown<String>();
    this.disabled = Output.createUnknown<bool>();
    this.eventType = Output.createUnknown<String>();
    this.filename = Output.createUnknown<String>();
    this.filter = Output.createUnknown<String>();
    this.gitFileSource = Output.createUnknown<GitFileSourceResponse>();
    this.github = Output.createUnknown<GitHubEventsConfigResponse>();
    this.gitlabEnterpriseEventsConfig =
        Output.createUnknown<GitLabEventsConfigResponse>();
    this.ignoredFiles = Output.createUnknown<List<String>>();
    this.includeBuildLogs = Output.createUnknown<String>();
    this.includedFiles = Output.createUnknown<List<String>>();
    this.location = Output.createUnknown<String>();
    this.name = Output.createUnknown<String>();
    this.project = Output.createUnknown<String>();
    this.projectId = Output.createUnknown<String>();
    this.pubsubConfig = Output.createUnknown<PubsubConfigResponse>();
    this.repositoryEventConfig =
        Output.createUnknown<RepositoryEventConfigResponse>();
    this.resourceName = Output.createUnknown<String>();
    this.serviceAccount = Output.createUnknown<String>();
    this.sourceToBuild = Output.createUnknown<GitRepoSourceResponse>();
    this.substitutions = Output.createUnknown<Map<String, String>>();
    this.tags = Output.createUnknown<List<String>>();
    this.triggerTemplate = Output.createUnknown<RepoSourceResponse>();
    this.webhookConfig = Output.createUnknown<WebhookConfigResponse>();
  }
}
