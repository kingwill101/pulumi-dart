import 'package:pulumi/pulumi.dart';
import 'artifacts_response.dart';
import 'build_approval_response.dart';
import 'build_options_response.dart';
import 'build_step_response.dart';
import 'failure_info_response.dart';
import 'results_response.dart';
import 'secret_response.dart';
import 'secrets_response.dart';
import 'source_provenance_response.dart';
import 'source_response.dart';
import 'warning_response.dart';

/// Result data returned by getBuild.
class GetBuildResult {
  /// Describes this build's approval configuration, status, and result.
  final BuildApprovalResponse approval;

  /// Artifacts produced by the build that should be uploaded upon successful completion of all build steps.
  final ArtifactsResponse artifacts;

  /// Secrets and secret environment variables.
  final SecretsResponse availableSecrets;

  /// The ID of the `BuildTrigger` that triggered this build, if it was triggered automatically.
  final String buildTriggerId;

  /// Time at which the request to create the build was received.
  final String createTime;

  /// Contains information about the build when status=FAILURE.
  final FailureInfoResponse failureInfo;

  /// Time at which execution of the build was finished. The difference between finish_time and start_time is the duration of the build's execution.
  final String finishTime;

  /// A list of images to be pushed upon the successful completion of all build steps. The images are pushed using the builder service account's credentials. The digests of the pushed images will be stored in the `Build` resource's results field. If any of the images fail to be pushed, the build status is marked `FAILURE`.
  final List<String> images;

  /// URL to logs for this build in Google Cloud Console.
  final String logUrl;

  /// Cloud Storage bucket where logs should be written (see [Bucket Name Requirements](https://cloud.google.com/storage/docs/bucket-naming#requirements)). Logs file names will be of the format `${logs_bucket}/log-${build_id}.txt`.
  final String logsBucket;

  /// The 'Build' name with format: `projects/{project}/locations/{location}/builds/{build}`, where {build} is a unique identifier generated by the service.
  final String name;

  /// Special options for this build.
  final BuildOptionsResponse options;

  /// ID of the project.
  final String project;

  /// TTL in queue for this build. If provided and the build is enqueued longer than this value, the build will expire and the build status will be `EXPIRED`. The TTL starts ticking from create_time.
  final String queueTtl;

  /// Results of the build.
  final ResultsResponse results;

  /// Secrets to decrypt using Cloud Key Management Service. Note: Secret Manager is the recommended technique for managing sensitive data with Cloud Build. Use `available_secrets` to configure builds to access secrets from Secret Manager. For instructions, see: https://cloud.google.com/cloud-build/docs/securing-builds/use-secrets
  final List<SecretResponse> secrets;

  /// IAM service account whose credentials will be used at build runtime. Must be of the format `projects/{PROJECT_ID}/serviceAccounts/{ACCOUNT}`. ACCOUNT can be email address or uniqueId of the service account.
  final String serviceAccount;

  /// The location of the source files to build.
  final SourceResponse source;

  /// A permanent fixed identifier for source.
  final SourceProvenanceResponse sourceProvenance;

  /// Time at which execution of the build was started.
  final String startTime;

  /// Status of the build.
  final String status;

  /// Customer-readable message about the current status.
  final String statusDetail;

  /// The operations to be performed on the workspace.
  final List<BuildStepResponse> steps;

  /// Substitutions data for `Build` resource.
  final Map<String, String> substitutions;

  /// Tags for annotation of a `Build`. These are not docker tags.
  final List<String> tags;

  /// Amount of time that this build should be allowed to run, to second granularity. If this amount of time elapses, work on the build will cease and the build status will be `TIMEOUT`. `timeout` starts ticking from `startTime`. Default time is 60 minutes.
  final String timeout;

  /// Stores timing information for phases of the build. Valid keys are: * BUILD: time to execute all build steps. * PUSH: time to push all artifacts including docker images and non docker artifacts. * FETCHSOURCE: time to fetch source. * SETUPBUILD: time to set up build. If the build does not specify source or images, these keys will not be included.
  final Map<String, String> timing;

  /// Non-fatal problems encountered during the execution of the build.
  final List<WarningResponse> warnings;

  GetBuildResult({
    required this.approval,
    required this.artifacts,
    required this.availableSecrets,
    required this.buildTriggerId,
    required this.createTime,
    required this.failureInfo,
    required this.finishTime,
    required this.images,
    required this.logUrl,
    required this.logsBucket,
    required this.name,
    required this.options,
    required this.project,
    required this.queueTtl,
    required this.results,
    required this.secrets,
    required this.serviceAccount,
    required this.source,
    required this.sourceProvenance,
    required this.startTime,
    required this.status,
    required this.statusDetail,
    required this.steps,
    required this.substitutions,
    required this.tags,
    required this.timeout,
    required this.timing,
    required this.warnings,
  });

  Map<String, dynamic> toMap() {
    final map = <String, dynamic>{};
    map['approval'] = approval.toMap();
    map['artifacts'] = artifacts.toMap();
    map['availableSecrets'] = availableSecrets.toMap();
    map['buildTriggerId'] = buildTriggerId;
    map['createTime'] = createTime;
    map['failureInfo'] = failureInfo.toMap();
    map['finishTime'] = finishTime;
    map['images'] = images;
    map['logUrl'] = logUrl;
    map['logsBucket'] = logsBucket;
    map['name'] = name;
    map['options'] = options.toMap();
    map['project'] = project;
    map['queueTtl'] = queueTtl;
    map['results'] = results.toMap();
    map['secrets'] = Input.encodeList<SecretResponse, Map<String, dynamic>>(
        secrets, (value) => value.toMap());
    map['serviceAccount'] = serviceAccount;
    map['source'] = source.toMap();
    map['sourceProvenance'] = sourceProvenance.toMap();
    map['startTime'] = startTime;
    map['status'] = status;
    map['statusDetail'] = statusDetail;
    map['steps'] = Input.encodeList<BuildStepResponse, Map<String, dynamic>>(
        steps, (value) => value.toMap());
    map['substitutions'] = substitutions;
    map['tags'] = tags;
    map['timeout'] = timeout;
    map['timing'] = timing;
    map['warnings'] = Input.encodeList<WarningResponse, Map<String, dynamic>>(
        warnings, (value) => value.toMap());
    return map;
  }

  factory GetBuildResult.fromMap(Map<String, dynamic> map) {
    return GetBuildResult(
      approval: BuildApprovalResponse.fromMap(
          (map['approval'] as Map).cast<String, dynamic>()),
      artifacts: ArtifactsResponse.fromMap(
          (map['artifacts'] as Map).cast<String, dynamic>()),
      availableSecrets: SecretsResponse.fromMap(
          (map['availableSecrets'] as Map).cast<String, dynamic>()),
      buildTriggerId: map['buildTriggerId'] as String,
      createTime: map['createTime'] as String,
      failureInfo: FailureInfoResponse.fromMap(
          (map['failureInfo'] as Map).cast<String, dynamic>()),
      finishTime: map['finishTime'] as String,
      images: (map['images'] as List).cast<String>(),
      logUrl: map['logUrl'] as String,
      logsBucket: map['logsBucket'] as String,
      name: map['name'] as String,
      options: BuildOptionsResponse.fromMap(
          (map['options'] as Map).cast<String, dynamic>()),
      project: map['project'] as String,
      queueTtl: map['queueTtl'] as String,
      results: ResultsResponse.fromMap(
          (map['results'] as Map).cast<String, dynamic>()),
      secrets: Input.decodeList<SecretResponse>(
          map['secrets'],
          (value) =>
              SecretResponse.fromMap((value as Map).cast<String, dynamic>())),
      serviceAccount: map['serviceAccount'] as String,
      source: SourceResponse.fromMap(
          (map['source'] as Map).cast<String, dynamic>()),
      sourceProvenance: SourceProvenanceResponse.fromMap(
          (map['sourceProvenance'] as Map).cast<String, dynamic>()),
      startTime: map['startTime'] as String,
      status: map['status'] as String,
      statusDetail: map['statusDetail'] as String,
      steps: Input.decodeList<BuildStepResponse>(
          map['steps'],
          (value) => BuildStepResponse.fromMap(
              (value as Map).cast<String, dynamic>())),
      substitutions: (map['substitutions'] as Map).cast<String, String>(),
      tags: (map['tags'] as List).cast<String>(),
      timeout: map['timeout'] as String,
      timing: (map['timing'] as Map).cast<String, String>(),
      warnings: Input.decodeList<WarningResponse>(
          map['warnings'],
          (value) =>
              WarningResponse.fromMap((value as Map).cast<String, dynamic>())),
    );
  }
}
