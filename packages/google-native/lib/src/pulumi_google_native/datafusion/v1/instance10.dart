import 'package:pulumi/pulumi.dart';
import 'accelerator_response2.dart';
import 'crypto_key_config_response.dart';
import 'event_publish_config_response.dart';
import 'instance_args10.dart';
import 'network_config_response11.dart';
import 'version_response4.dart';

/// Creates a new Data Fusion instance in the specified project and location.
/// Auto-naming is currently not supported for this resource.
class Instance10 extends CustomResource {
  /// List of accelerators enabled for this CDF instance.
  late final Output<List<AcceleratorResponse2>> accelerators;

  /// Endpoint on which the REST APIs is accessible.
  late final Output<String> apiEndpoint;

  /// Available versions that the instance can be upgraded to using UpdateInstanceRequest.
  late final Output<List<VersionResponse4>> availableVersion;

  /// The time the instance was created.
  late final Output<String> createTime;

  /// The crypto key configuration. This field is used by the Customer-Managed Encryption Keys (CMEK) feature.
  late final Output<CryptoKeyConfigResponse> cryptoKeyConfig;

  /// User-managed service account to set on Dataproc when Cloud Data Fusion creates Dataproc to run data processing pipelines. This allows users to have fine-grained access control on Dataproc's accesses to cloud resources.
  late final Output<String> dataprocServiceAccount;

  /// A description of this instance.
  late final Output<String> description;

  /// If the instance state is DISABLED, the reason for disabling the instance.
  late final Output<List<String>> disabledReason;

  /// Display name for an instance.
  late final Output<String> displayName;

  /// Option to enable granular role-based access control.
  late final Output<bool> enableRbac;

  /// Option to enable Stackdriver Logging.
  late final Output<bool> enableStackdriverLogging;

  /// Option to enable Stackdriver Monitoring.
  late final Output<bool> enableStackdriverMonitoring;

  /// Option to enable granular zone separation.
  late final Output<bool> enableZoneSeparation;

  /// Option to enable and pass metadata for event publishing.
  late final Output<EventPublishConfigResponse> eventPublishConfig;

  /// Cloud Storage bucket generated by Data Fusion in the customer project.
  late final Output<String> gcsBucket;

  /// Required. The name of the instance to create.
  late final Output<String> instanceId;

  /// The resource labels for instance to use to annotate any related underlying resources such as Compute Engine VMs. The character '=' is not allowed to be used within the labels.
  late final Output<Map<String, String>> labels;
  late final Output<String> location;

  /// The name of this instance is in the form of projects/{project}/locations/{location}/instances/{instance}.
  late final Output<String> name;

  /// Network configuration options. These are required when a private Data Fusion instance is to be created.
  late final Output<NetworkConfigResponse11> networkConfig;

  /// Map of additional options used to configure the behavior of Data Fusion instance.
  late final Output<Map<String, String>> options;

  /// P4 service account for the customer project.
  late final Output<String> p4ServiceAccount;

  /// Optional. Current patch revision of the Data Fusion.
  late final Output<String> patchRevision;

  /// Specifies whether the Data Fusion instance should be private. If set to true, all Data Fusion nodes will have private IP addresses and will not be able to access the public internet.
  late final Output<bool> privateInstance;
  late final Output<String> project;

  /// Reserved for future use.
  late final Output<bool> satisfiesPzs;

  /// Deprecated. Use tenant_project_id instead to extract the tenant project ID.
  late final Output<String> serviceAccount;

  /// Endpoint on which the Data Fusion UI is accessible.
  late final Output<String> serviceEndpoint;

  /// The current state of this Data Fusion instance.
  late final Output<String> state;

  /// Additional information about the current state of this Data Fusion instance if available.
  late final Output<String> stateMessage;

  /// The name of the tenant project.
  late final Output<String> tenantProjectId;

  /// Instance type.
  late final Output<String> type;

  /// The time the instance was last updated.
  late final Output<String> updateTime;

  /// Current version of the Data Fusion. Only specifiable in Update.
  late final Output<String> version;

  /// Endpoint on which the Data Fusion UI is accessible to third-party users
  late final Output<String> workforceIdentityServiceEndpoint;

  /// Name of the zone in which the Data Fusion instance will be created. Only DEVELOPER instances use this field.
  late final Output<String> zone;

  Instance10(
    String name, {
    InstanceArgs10? args,
    CustomResourceOptions? options,
  }) : super(
          'google-native:datafusion/v1:Instance',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.accelerators = Output.createUnknown<List<AcceleratorResponse2>>();
    this.apiEndpoint = Output.createUnknown<String>();
    this.availableVersion = Output.createUnknown<List<VersionResponse4>>();
    this.createTime = Output.createUnknown<String>();
    this.cryptoKeyConfig = Output.createUnknown<CryptoKeyConfigResponse>();
    this.dataprocServiceAccount = Output.createUnknown<String>();
    this.description = Output.createUnknown<String>();
    this.disabledReason = Output.createUnknown<List<String>>();
    this.displayName = Output.createUnknown<String>();
    this.enableRbac = Output.createUnknown<bool>();
    this.enableStackdriverLogging = Output.createUnknown<bool>();
    this.enableStackdriverMonitoring = Output.createUnknown<bool>();
    this.enableZoneSeparation = Output.createUnknown<bool>();
    this.eventPublishConfig =
        Output.createUnknown<EventPublishConfigResponse>();
    this.gcsBucket = Output.createUnknown<String>();
    this.instanceId = Output.createUnknown<String>();
    this.labels = Output.createUnknown<Map<String, String>>();
    this.location = Output.createUnknown<String>();
    this.name = Output.createUnknown<String>();
    this.networkConfig = Output.createUnknown<NetworkConfigResponse11>();
    this.options = Output.createUnknown<Map<String, String>>();
    this.p4ServiceAccount = Output.createUnknown<String>();
    this.patchRevision = Output.createUnknown<String>();
    this.privateInstance = Output.createUnknown<bool>();
    this.project = Output.createUnknown<String>();
    this.satisfiesPzs = Output.createUnknown<bool>();
    this.serviceAccount = Output.createUnknown<String>();
    this.serviceEndpoint = Output.createUnknown<String>();
    this.state = Output.createUnknown<String>();
    this.stateMessage = Output.createUnknown<String>();
    this.tenantProjectId = Output.createUnknown<String>();
    this.type = Output.createUnknown<String>();
    this.updateTime = Output.createUnknown<String>();
    this.version = Output.createUnknown<String>();
    this.workforceIdentityServiceEndpoint = Output.createUnknown<String>();
    this.zone = Output.createUnknown<String>();
  }
}
