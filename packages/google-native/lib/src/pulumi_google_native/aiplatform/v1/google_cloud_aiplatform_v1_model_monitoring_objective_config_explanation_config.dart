import 'google_cloud_aiplatform_v1_model_monitoring_objective_config_explanation_config_explanation_baseline.dart';

/// The config for integrating with Vertex Explainable AI. Only applicable if the Model has explanation_spec populated.
class GoogleCloudAiplatformV1ModelMonitoringObjectiveConfigExplanationConfig {
  /// If want to analyze the Vertex Explainable AI feature attribute scores or not. If set to true, Vertex AI will log the feature attributions from explain response and do the skew/drift detection for them.
  final bool? enableFeatureAttributes;

  /// Predictions generated by the BatchPredictionJob using baseline dataset.
  final GoogleCloudAiplatformV1ModelMonitoringObjectiveConfigExplanationConfigExplanationBaseline?
      explanationBaseline;

  GoogleCloudAiplatformV1ModelMonitoringObjectiveConfigExplanationConfig({
    this.enableFeatureAttributes,
    this.explanationBaseline,
  });

  Map<String, dynamic> toMap() {
    final map = <String, dynamic>{};
    final enableFeatureAttributesValue = enableFeatureAttributes;
    if (enableFeatureAttributesValue != null) {
      map['enableFeatureAttributes'] = enableFeatureAttributesValue;
    }
    final explanationBaselineValue = explanationBaseline;
    if (explanationBaselineValue != null) {
      map['explanationBaseline'] = explanationBaselineValue.toMap();
    }
    return map;
  }

  factory GoogleCloudAiplatformV1ModelMonitoringObjectiveConfigExplanationConfig.fromMap(
      Map<String, dynamic> map) {
    return GoogleCloudAiplatformV1ModelMonitoringObjectiveConfigExplanationConfig(
      enableFeatureAttributes: map['enableFeatureAttributes'] == null
          ? null
          : map['enableFeatureAttributes'] as bool,
      explanationBaseline: map['explanationBaseline'] == null
          ? null
          : GoogleCloudAiplatformV1ModelMonitoringObjectiveConfigExplanationConfigExplanationBaseline
              .fromMap(
                  (map['explanationBaseline'] as Map).cast<String, dynamic>()),
    );
  }
}
