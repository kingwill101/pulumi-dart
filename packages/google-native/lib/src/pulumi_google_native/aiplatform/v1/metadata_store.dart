import 'package:pulumi/pulumi.dart' hide Config;
import 'google_cloud_aiplatform_v1_encryption_spec_response.dart';
import 'google_cloud_aiplatform_v1_metadata_store_metadata_store_state_response.dart';
import 'metadata_store_args.dart';

/// Initializes a MetadataStore, including allocation of resources.
/// Auto-naming is currently not supported for this resource.
class MetadataStore extends CustomResource {
  /// Timestamp when this MetadataStore was created.
  late final Output<String> createTime;

  /// Description of the MetadataStore.
  late final Output<String> description;

  /// Customer-managed encryption key spec for a Metadata Store. If set, this Metadata Store and all sub-resources of this Metadata Store are secured using this key.
  late final Output<GoogleCloudAiplatformV1EncryptionSpecResponse>
      encryptionSpec;
  late final Output<String> location;

  /// The {metadatastore} portion of the resource name with the format: `projects/{project}/locations/{location}/metadataStores/{metadatastore}` If not provided, the MetadataStore's ID will be a UUID generated by the service. Must be 4-128 characters in length. Valid characters are `/a-z-/`. Must be unique across all MetadataStores in the parent Location. (Otherwise the request will fail with ALREADY_EXISTS, or PERMISSION_DENIED if the caller can't view the preexisting MetadataStore.)
  late final Output<String?> metadataStoreId;

  /// The resource name of the MetadataStore instance.
  late final Output<String> name;
  late final Output<String> project;

  /// State information of the MetadataStore.
  late final Output<
      GoogleCloudAiplatformV1MetadataStoreMetadataStoreStateResponse> state;

  /// Timestamp when this MetadataStore was last updated.
  late final Output<String> updateTime;

  MetadataStore(
    String name, {
    MetadataStoreArgs? args,
    CustomResourceOptions? options,
  }) : super(
          'google-native:aiplatform/v1:MetadataStore',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.createTime = registerOutput<String>('createTime');
    this.description = registerOutput<String>('description');
    this.encryptionSpec =
        registerOutput<GoogleCloudAiplatformV1EncryptionSpecResponse>(
            'encryptionSpec');
    this.location = registerOutput<String>('location');
    this.metadataStoreId = registerOutput<String?>('metadataStoreId');
    this.name = registerOutput<String>('name');
    this.project = registerOutput<String>('project');
    this.state = registerOutput<
            GoogleCloudAiplatformV1MetadataStoreMetadataStoreStateResponse>(
        'state');
    this.updateTime = registerOutput<String>('updateTime');
  }
}
