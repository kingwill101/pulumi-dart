import 'package:pulumi/pulumi.dart';
import 'credential_response.dart';
import 'deployment_args2.dart';
import 'deployment_label_entry_response.dart';
import 'deployment_output_entry_response.dart';
import 'deployment_update_response.dart';
import 'operation_response2.dart';
import 'target_configuration_response.dart';

/// Creates a deployment and all of the resources described by the deployment manifest.
class DeploymentType6 extends CustomResource {
  /// Sets the policy to use for creating new resources.
  late final Output<String?> createPolicy;

  /// User provided default credential for the deployment.
  late final Output<CredentialResponse> credential;

  /// An optional user-provided description of the deployment.
  late final Output<String> description;

  /// Provides a fingerprint to use in requests to modify a deployment, such as `update()`, `stop()`, and `cancelPreview()` requests. A fingerprint is a randomly generated value that must be provided with `update()`, `stop()`, and `cancelPreview()` requests to perform optimistic locking. This ensures optimistic concurrency so that only one request happens at a time. The fingerprint is initially generated by Deployment Manager and changes after every request to modify data. To get the latest fingerprint value, perform a `get()` request to a deployment.
  late final Output<String> fingerprint;

  /// Creation timestamp in RFC3339 text format.
  late final Output<String> insertTime;

  /// Map of One Platform labels; provided by the client when the resource is created or updated. Specifically: Label keys must be between 1 and 63 characters long and must conform to the following regular expression: `[a-z]([-a-z0-9]*[a-z0-9])?` Label values must be between 0 and 63 characters long and must conform to the regular expression `([a-z]([-a-z0-9]*[a-z0-9])?)?`.
  late final Output<List<DeploymentLabelEntryResponse>> labels;

  /// URL of the manifest representing the last manifest that was successfully deployed. If no manifest has been successfully deployed, this field will be absent.
  late final Output<String> manifest;

  /// Name of the resource; provided by the client when the resource is created. The name must be 1-63 characters long, and comply with RFC1035. Specifically, the name must be 1-63 characters long and match the regular expression `[a-z]([-a-z0-9]*[a-z0-9])?` which means the first character must be a lowercase letter, and all following characters must be a dash, lowercase letter, or digit, except the last character, which cannot be a dash.
  late final Output<String> name;

  /// The Operation that most recently ran, or is currently running, on this deployment.
  late final Output<OperationResponse2> operation;

  /// List of outputs from the last manifest that deployed successfully.
  late final Output<List<DeploymentOutputEntryResponse>> outputs;

  /// If set to true, creates a deployment and creates "shell" resources but does not actually instantiate these resources. This allows you to preview what your deployment looks like. After previewing a deployment, you can deploy your resources by making a request with the `update()` method or you can use the `cancelPreview()` method to cancel the preview altogether. Note that the deployment will still exist after you cancel the preview and you must separately delete this deployment if you want to remove it.
  late final Output<bool?> preview;
  late final Output<String> project;

  /// Server defined URL for the resource.
  late final Output<String> selfLink;

  /// [Input Only] The parameters that define your deployment, including the deployment configuration and relevant templates.
  late final Output<TargetConfigurationResponse> target;

  /// If Deployment Manager is currently updating or previewing an update to this deployment, the updated configuration appears here.
  late final Output<DeploymentUpdateResponse> update;

  /// Update timestamp in RFC3339 text format.
  late final Output<String> updateTime;

  DeploymentType6(
    String name, {
    DeploymentArgs2? args,
    CustomResourceOptions? options,
  }) : super(
          'google-native:deploymentmanager/alpha:Deployment',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.createPolicy = Output.createUnknown<String?>();
    this.credential = Output.createUnknown<CredentialResponse>();
    this.description = Output.createUnknown<String>();
    this.fingerprint = Output.createUnknown<String>();
    this.insertTime = Output.createUnknown<String>();
    this.labels = Output.createUnknown<List<DeploymentLabelEntryResponse>>();
    this.manifest = Output.createUnknown<String>();
    this.name = Output.createUnknown<String>();
    this.operation = Output.createUnknown<OperationResponse2>();
    this.outputs = Output.createUnknown<List<DeploymentOutputEntryResponse>>();
    this.preview = Output.createUnknown<bool?>();
    this.project = Output.createUnknown<String>();
    this.selfLink = Output.createUnknown<String>();
    this.target = Output.createUnknown<TargetConfigurationResponse>();
    this.update = Output.createUnknown<DeploymentUpdateResponse>();
    this.updateTime = Output.createUnknown<String>();
  }
}
