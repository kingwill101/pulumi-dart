// ignore_for_file: unused_element, unnecessary_cast

import 'execution_template_response.dart';

/// The definition of a single executed notebook.
class ExecutionResponse {
  /// Time the Execution was instantiated.
  final String createTime;

  /// A brief description of this execution.
  final String description;

  /// Name used for UI purposes. Name can only contain alphanumeric characters and underscores '_'.
  final String displayName;

  /// execute metadata including name, hardware spec, region, labels, etc.
  final ExecutionTemplateResponse executionTemplate;

  /// The URI of the external job used to execute the notebook.
  final String jobUri;

  /// The resource name of the execute. Format: `projects/{project_id}/locations/{location}/executions/{execution_id}`
  final String name;

  /// Output notebook file generated by this execution
  final String outputNotebookFile;

  /// State of the underlying AI Platform job.
  final String state;

  /// Time the Execution was last updated.
  final String updateTime;

  ExecutionResponse({
    required this.createTime,
    required this.description,
    required this.displayName,
    required this.executionTemplate,
    required this.jobUri,
    required this.name,
    required this.outputNotebookFile,
    required this.state,
    required this.updateTime,
  });

  Map<String, dynamic> toMap() {
    final map = <String, dynamic>{};
    map['createTime'] = createTime;
    map['description'] = description;
    map['displayName'] = displayName;
    map['executionTemplate'] = executionTemplate.toMap();
    map['jobUri'] = jobUri;
    map['name'] = name;
    map['outputNotebookFile'] = outputNotebookFile;
    map['state'] = state;
    map['updateTime'] = updateTime;
    return map;
  }

  factory ExecutionResponse.fromMap(Map<String, dynamic> map) {
    return ExecutionResponse(
      createTime: map['createTime'] as String,
      description: map['description'] as String,
      displayName: map['displayName'] as String,
      executionTemplate: ExecutionTemplateResponse.fromMap(
          (map['executionTemplate'] as Map).cast<String, dynamic>()),
      jobUri: map['jobUri'] as String,
      name: map['name'] as String,
      outputNotebookFile: map['outputNotebookFile'] as String,
      state: map['state'] as String,
      updateTime: map['updateTime'] as String,
    );
  }
}
