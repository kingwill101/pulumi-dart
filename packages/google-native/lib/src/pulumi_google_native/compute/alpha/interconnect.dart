import 'package:pulumi/pulumi.dart';
import 'interconnect_args.dart';
import 'interconnect_circuit_info_response.dart';
import 'interconnect_macsec_response.dart';
import 'interconnect_outage_notification_response.dart';

/// Creates an Interconnect in the specified project using the data included in the request.
class Interconnect extends CustomResource {
  /// Administrative status of the interconnect. When this is set to true, the Interconnect is functional and can carry traffic. When set to false, no packets can be carried over the interconnect and no BGP routes are exchanged over it. By default, the status is set to true.
  late final Output<bool> adminEnabled;

  /// [Output only] List of features available for this Interconnect connection, which can take one of the following values: - MACSEC If present then the Interconnect connection is provisioned on MACsec capable hardware ports. If not present then the Interconnect connection is provisioned on non-MACsec capable ports and MACsec isn't supported and enabling MACsec fails.
  late final Output<List<String>> availableFeatures;

  /// A list of CircuitInfo objects, that describe the individual circuits in this LAG.
  late final Output<List<InterconnectCircuitInfoResponse>> circuitInfos;

  /// Creation timestamp in RFC3339 text format.
  late final Output<String> creationTimestamp;

  /// Customer name, to put in the Letter of Authorization as the party authorized to request a crossconnect.
  late final Output<String> customerName;

  /// An optional description of this resource. Provide this property when you create the resource.
  late final Output<String> description;

  /// A list of outages expected for this Interconnect.
  late final Output<List<InterconnectOutageNotificationResponse>>
      expectedOutages;

  /// IP address configured on the Google side of the Interconnect link. This can be used only for ping tests.
  late final Output<String> googleIpAddress;

  /// Google reference ID to be used when raising support tickets with Google or otherwise to debug backend connectivity issues.
  late final Output<String> googleReferenceId;

  /// A list of the URLs of all InterconnectAttachments configured to use this Interconnect.
  late final Output<List<String>> interconnectAttachments;

  /// Type of interconnect, which can take one of the following values: - PARTNER: A partner-managed interconnection shared between customers though a partner. - DEDICATED: A dedicated physical interconnection with the customer. Note that a value IT_PRIVATE has been deprecated in favor of DEDICATED.
  late final Output<String> interconnectType;

  /// Type of the resource. Always compute#interconnect for interconnects.
  late final Output<String> kind;

  /// A fingerprint for the labels being applied to this Interconnect, which is essentially a hash of the labels set used for optimistic locking. The fingerprint is initially generated by Compute Engine and changes after every request to modify or update labels. You must always provide an up-to-date fingerprint hash in order to update or change labels, otherwise the request will fail with error 412 conditionNotMet. To see the latest fingerprint, make a get() request to retrieve an Interconnect.
  late final Output<String> labelFingerprint;

  /// Labels for this resource. These can only be added or modified by the setLabels method. Each label key/value pair must comply with RFC1035. Label values may be empty.
  late final Output<Map<String, String>> labels;

  /// Type of link requested, which can take one of the following values: - LINK_TYPE_ETHERNET_10G_LR: A 10G Ethernet with LR optics - LINK_TYPE_ETHERNET_100G_LR: A 100G Ethernet with LR optics. Note that this field indicates the speed of each of the links in the bundle, not the speed of the entire bundle.
  late final Output<String> linkType;

  /// URL of the InterconnectLocation object that represents where this connection is to be provisioned.
  late final Output<String> location;

  /// Configuration that enables Media Access Control security (MACsec) on the Cloud Interconnect connection between Google and your on-premises router.
  late final Output<InterconnectMacsecResponse> macsec;

  /// Enable or disable MACsec on this Interconnect connection. MACsec enablement fails if the MACsec object is not specified.
  late final Output<bool> macsecEnabled;

  /// Name of the resource. Provided by the client when the resource is created. The name must be 1-63 characters long, and comply with RFC1035. Specifically, the name must be 1-63 characters long and match the regular expression `[a-z]([-a-z0-9]*[a-z0-9])?` which means the first character must be a lowercase letter, and all following characters must be a dash, lowercase letter, or digit, except the last character, which cannot be a dash.
  late final Output<String> name;

  /// Email address to contact the customer NOC for operations and maintenance notifications regarding this Interconnect. If specified, this will be used for notifications in addition to all other forms described, such as Cloud Monitoring logs alerting and Cloud Notifications. This field is required for users who sign up for Cloud Interconnect using workforce identity federation.
  late final Output<String> nocContactEmail;

  /// The current status of this Interconnect's functionality, which can take one of the following values: - OS_ACTIVE: A valid Interconnect, which is turned up and is ready to use. Attachments may be provisioned on this Interconnect. - OS_UNPROVISIONED: An Interconnect that has not completed turnup. No attachments may be provisioned on this Interconnect. - OS_UNDER_MAINTENANCE: An Interconnect that is undergoing internal maintenance. No attachments may be provisioned or updated on this Interconnect.
  late final Output<String> operationalStatus;

  /// IP address configured on the customer side of the Interconnect link. The customer should configure this IP address during turnup when prompted by Google NOC. This can be used only for ping tests.
  late final Output<String> peerIpAddress;
  late final Output<String> project;

  /// Number of links actually provisioned in this interconnect.
  late final Output<int> provisionedLinkCount;

  /// Indicates that this is a Cross-Cloud Interconnect. This field specifies the location outside of Google's network that the interconnect is connected to.
  late final Output<String> remoteLocation;

  /// An optional request ID to identify requests. Specify a unique request ID so that if you must retry your request, the server will know to ignore the request if it has already been completed. For example, consider a situation where you make an initial request and the request times out. If you make the request again with the same request ID, the server can check if original operation with the same request ID was received, and if so, will ignore the second request. This prevents clients from accidentally creating duplicate commitments. The request ID must be a valid UUID with the exception that zero UUID is not supported ( 00000000-0000-0000-0000-000000000000).
  late final Output<String?> requestId;

  /// Optional. List of features requested for this Interconnect connection, which can take one of the following values: - MACSEC If specified then the connection is created on MACsec capable hardware ports. If not specified, the default value is false, which allocates non-MACsec capable ports first if available. This parameter can be provided only with Interconnect INSERT. It isn't valid for Interconnect PATCH.
  late final Output<List<String>> requestedFeatures;

  /// Target number of physical links in the link bundle, as requested by the customer.
  late final Output<int> requestedLinkCount;

  /// Reserved for future use.
  late final Output<bool> satisfiesPzs;

  /// Server-defined URL for the resource.
  late final Output<String> selfLink;

  /// Server-defined URL for this resource with the resource id.
  late final Output<String> selfLinkWithId;

  /// The current state of Interconnect functionality, which can take one of the following values: - ACTIVE: The Interconnect is valid, turned up and ready to use. Attachments may be provisioned on this Interconnect. - UNPROVISIONED: The Interconnect has not completed turnup. No attachments may be provisioned on this Interconnect. - UNDER_MAINTENANCE: The Interconnect is undergoing internal maintenance. No attachments may be provisioned or updated on this Interconnect.
  late final Output<String> state;

  Interconnect(
    String name, {
    InterconnectArgs? args,
    CustomResourceOptions? options,
  }) : super(
          'google-native:compute/alpha:Interconnect',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.adminEnabled = Output.createUnknown<bool>();
    this.availableFeatures = Output.createUnknown<List<String>>();
    this.circuitInfos =
        Output.createUnknown<List<InterconnectCircuitInfoResponse>>();
    this.creationTimestamp = Output.createUnknown<String>();
    this.customerName = Output.createUnknown<String>();
    this.description = Output.createUnknown<String>();
    this.expectedOutages =
        Output.createUnknown<List<InterconnectOutageNotificationResponse>>();
    this.googleIpAddress = Output.createUnknown<String>();
    this.googleReferenceId = Output.createUnknown<String>();
    this.interconnectAttachments = Output.createUnknown<List<String>>();
    this.interconnectType = Output.createUnknown<String>();
    this.kind = Output.createUnknown<String>();
    this.labelFingerprint = Output.createUnknown<String>();
    this.labels = Output.createUnknown<Map<String, String>>();
    this.linkType = Output.createUnknown<String>();
    this.location = Output.createUnknown<String>();
    this.macsec = Output.createUnknown<InterconnectMacsecResponse>();
    this.macsecEnabled = Output.createUnknown<bool>();
    this.name = Output.createUnknown<String>();
    this.nocContactEmail = Output.createUnknown<String>();
    this.operationalStatus = Output.createUnknown<String>();
    this.peerIpAddress = Output.createUnknown<String>();
    this.project = Output.createUnknown<String>();
    this.provisionedLinkCount = Output.createUnknown<int>();
    this.remoteLocation = Output.createUnknown<String>();
    this.requestId = Output.createUnknown<String?>();
    this.requestedFeatures = Output.createUnknown<List<String>>();
    this.requestedLinkCount = Output.createUnknown<int>();
    this.satisfiesPzs = Output.createUnknown<bool>();
    this.selfLink = Output.createUnknown<String>();
    this.selfLinkWithId = Output.createUnknown<String>();
    this.state = Output.createUnknown<String>();
  }
}
