import 'application_endpoint_response.dart';
import 'gateway_response.dart';

/// Result data returned by getConnection.
class GetConnectionResult {
  /// Address of the remote application endpoint for the BeyondCorp Connection.
  final ApplicationEndpointResponse applicationEndpoint;

  /// Optional. List of [google.cloud.beyondcorp.v1main.Connector.name] that are authorised to be associated with this Connection.
  final List<String> connectors;

  /// Timestamp when the resource was created.
  final String createTime;

  /// Optional. An arbitrary user-provided name for the connection. Cannot exceed 64 characters.
  final String displayName;

  /// Optional. Gateway used by the connection.
  final GatewayResponse gateway;

  /// Optional. Resource labels to represent user provided metadata.
  final Map<String, String> labels;

  /// Unique resource name of the connection. The name is ignored when creating a connection.
  final String name;

  /// The current state of the connection.
  final String state;

  /// The type of network connectivity used by the connection.
  final String type;

  /// A unique identifier for the instance generated by the system.
  final String uid;

  /// Timestamp when the resource was last modified.
  final String updateTime;

  GetConnectionResult({
    required this.applicationEndpoint,
    required this.connectors,
    required this.createTime,
    required this.displayName,
    required this.gateway,
    required this.labels,
    required this.name,
    required this.state,
    required this.type,
    required this.uid,
    required this.updateTime,
  });

  Map<String, dynamic> toMap() {
    final map = <String, dynamic>{};
    map['applicationEndpoint'] = applicationEndpoint.toMap();
    map['connectors'] = connectors;
    map['createTime'] = createTime;
    map['displayName'] = displayName;
    map['gateway'] = gateway.toMap();
    map['labels'] = labels;
    map['name'] = name;
    map['state'] = state;
    map['type'] = type;
    map['uid'] = uid;
    map['updateTime'] = updateTime;
    return map;
  }

  factory GetConnectionResult.fromMap(Map<String, dynamic> map) {
    return GetConnectionResult(
      applicationEndpoint: ApplicationEndpointResponse.fromMap(
          (map['applicationEndpoint'] as Map).cast<String, dynamic>()),
      connectors: (map['connectors'] as List).cast<String>(),
      createTime: map['createTime'] as String,
      displayName: map['displayName'] as String,
      gateway: GatewayResponse.fromMap(
          (map['gateway'] as Map).cast<String, dynamic>()),
      labels: (map['labels'] as Map).cast<String, String>(),
      name: map['name'] as String,
      state: map['state'] as String,
      type: map['type'] as String,
      uid: map['uid'] as String,
      updateTime: map['updateTime'] as String,
    );
  }
}
