import 'package:pulumi/pulumi.dart';
import 'connector_args.dart';
import 'principal_info_response.dart';
import 'resource_info_response.dart';

/// Creates a new Connector in a given project and location.
class Connector extends CustomResource {
  /// Optional. User-settable connector resource ID. * Must start with a letter. * Must contain between 4-63 characters from `/a-z-/`. * Must end with a number or a letter.
  late final Output<String?> connectorId;

  /// Timestamp when the resource was created.
  late final Output<String> createTime;

  /// Optional. An arbitrary user-provided name for the connector. Cannot exceed 64 characters.
  late final Output<String> displayName;

  /// Optional. Resource labels to represent user provided metadata.
  late final Output<Map<String, String>> labels;
  late final Output<String> location;

  /// Unique resource name of the connector. The name is ignored when creating a connector.
  late final Output<String> name;

  /// Principal information about the Identity of the connector.
  late final Output<PrincipalInfoResponse> principalInfo;
  late final Output<String> project;

  /// Optional. An optional request ID to identify requests. Specify a unique request ID so that if you must retry your request, the server will know to ignore the request if it has already been completed. The server will guarantee that for at least 60 minutes since the first request. For example, consider a situation where you make an initial request and the request times out. If you make the request again with the same request ID, the server can check if original operation with the same request ID was received, and if so, will ignore the second request. This prevents clients from accidentally creating duplicate commitments. The request ID must be a valid UUID with the exception that zero UUID is not supported (00000000-0000-0000-0000-000000000000).
  late final Output<String?> requestId;

  /// Optional. Resource info of the connector.
  late final Output<ResourceInfoResponse> resourceInfo;

  /// The current state of the connector.
  late final Output<String> state;

  /// A unique identifier for the instance generated by the system.
  late final Output<String> uid;

  /// Timestamp when the resource was last modified.
  late final Output<String> updateTime;

  Connector(
    String name, {
    ConnectorArgs? args,
    CustomResourceOptions? options,
  }) : super(
          'google-native:beyondcorp/v1alpha:Connector',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.connectorId = Output.createUnknown<String?>();
    this.createTime = Output.createUnknown<String>();
    this.displayName = Output.createUnknown<String>();
    this.labels = Output.createUnknown<Map<String, String>>();
    this.location = Output.createUnknown<String>();
    this.name = Output.createUnknown<String>();
    this.principalInfo = Output.createUnknown<PrincipalInfoResponse>();
    this.project = Output.createUnknown<String>();
    this.requestId = Output.createUnknown<String?>();
    this.resourceInfo = Output.createUnknown<ResourceInfoResponse>();
    this.state = Output.createUnknown<String>();
    this.uid = Output.createUnknown<String>();
    this.updateTime = Output.createUnknown<String>();
  }
}
