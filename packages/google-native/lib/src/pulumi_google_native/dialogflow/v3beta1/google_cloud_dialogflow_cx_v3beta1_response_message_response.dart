/// Represents a response message that can be returned by a conversational agent. Response messages are also used for output audio synthesis. The approach is as follows: * If at least one OutputAudioText response is present, then all OutputAudioText responses are linearly concatenated, and the result is used for output audio synthesis. * If the OutputAudioText responses are a mixture of text and SSML, then the concatenated result is treated as SSML; otherwise, the result is treated as either text or SSML as appropriate. The agent designer should ideally use either text or SSML consistently throughout the bot design. * Otherwise, all Text responses are linearly concatenated, and the result is used for output audio synthesis. This approach allows for more sophisticated user experience scenarios, where the text displayed to the user may differ from what is heard.
class GoogleCloudDialogflowCxV3beta1ResponseMessageResponse {
  /// The channel which the response is associated with. Clients can specify the channel via QueryParameters.channel, and only associated channel response will be returned.
  final String channel;

  /// Indicates that the conversation succeeded.
  final GoogleCloudDialogflowCxV3beta1ResponseMessageConversationSuccessResponse
      conversationSuccess;

  /// A signal that indicates the interaction with the Dialogflow agent has ended. This message is generated by Dialogflow only when the conversation reaches `END_SESSION` page. It is not supposed to be defined by the user. It's guaranteed that there is at most one such message in each response.
  final Map<String, dynamic> endInteraction;

  /// Represents info card for knowledge answers, to be better rendered in Dialogflow Messenger.
  final Map<String, dynamic> knowledgeInfoCard;

  /// Hands off conversation to a human agent.
  final GoogleCloudDialogflowCxV3beta1ResponseMessageLiveAgentHandoffResponse
      liveAgentHandoff;

  /// An audio response message composed of both the synthesized Dialogflow agent responses and responses defined via play_audio. This message is generated by Dialogflow only and not supposed to be defined by the user.
  final GoogleCloudDialogflowCxV3beta1ResponseMessageMixedAudioResponse
      mixedAudio;

  /// A text or ssml response that is preferentially used for TTS output audio synthesis, as described in the comment on the ResponseMessage message.
  final GoogleCloudDialogflowCxV3beta1ResponseMessageOutputAudioTextResponse
      outputAudioText;

  /// Returns a response containing a custom, platform-specific payload.
  final Map<String, String> payload;

  /// Signal that the client should play an audio clip hosted at a client-specific URI. Dialogflow uses this to construct mixed_audio. However, Dialogflow itself does not try to read or process the URI in any way.
  final GoogleCloudDialogflowCxV3beta1ResponseMessagePlayAudioResponse
      playAudio;

  /// A signal that the client should transfer the phone call connected to this agent to a third-party endpoint.
  final GoogleCloudDialogflowCxV3beta1ResponseMessageTelephonyTransferCallResponse
      telephonyTransferCall;

  /// Returns a text response.
  final GoogleCloudDialogflowCxV3beta1ResponseMessageTextResponse text;

  GoogleCloudDialogflowCxV3beta1ResponseMessageResponse({
    required this.channel,
    required this.conversationSuccess,
    required this.endInteraction,
    required this.knowledgeInfoCard,
    required this.liveAgentHandoff,
    required this.mixedAudio,
    required this.outputAudioText,
    required this.payload,
    required this.playAudio,
    required this.telephonyTransferCall,
    required this.text,
  });

  Map<String, dynamic> toMap() {
    final map = <String, dynamic>{};
    map['channel'] = channel;
    map['conversationSuccess'] = conversationSuccess.toMap();
    map['endInteraction'] = endInteraction;
    map['knowledgeInfoCard'] = knowledgeInfoCard;
    map['liveAgentHandoff'] = liveAgentHandoff.toMap();
    map['mixedAudio'] = mixedAudio.toMap();
    map['outputAudioText'] = outputAudioText.toMap();
    map['payload'] = payload;
    map['playAudio'] = playAudio.toMap();
    map['telephonyTransferCall'] = telephonyTransferCall.toMap();
    map['text'] = text.toMap();
    return map;
  }

  factory GoogleCloudDialogflowCxV3beta1ResponseMessageResponse.fromMap(
      Map<String, dynamic> map) {
    return GoogleCloudDialogflowCxV3beta1ResponseMessageResponse(
      channel: map['channel'] as String,
      conversationSuccess:
          GoogleCloudDialogflowCxV3beta1ResponseMessageConversationSuccessResponse
              .fromMap(
                  (map['conversationSuccess'] as Map).cast<String, dynamic>()),
      endInteraction: (map['endInteraction'] as Map).cast<String, dynamic>(),
      knowledgeInfoCard:
          (map['knowledgeInfoCard'] as Map).cast<String, dynamic>(),
      liveAgentHandoff:
          GoogleCloudDialogflowCxV3beta1ResponseMessageLiveAgentHandoffResponse
              .fromMap(
                  (map['liveAgentHandoff'] as Map).cast<String, dynamic>()),
      mixedAudio:
          GoogleCloudDialogflowCxV3beta1ResponseMessageMixedAudioResponse
              .fromMap((map['mixedAudio'] as Map).cast<String, dynamic>()),
      outputAudioText:
          GoogleCloudDialogflowCxV3beta1ResponseMessageOutputAudioTextResponse
              .fromMap((map['outputAudioText'] as Map).cast<String, dynamic>()),
      payload: (map['payload'] as Map).cast<String, String>(),
      playAudio: GoogleCloudDialogflowCxV3beta1ResponseMessagePlayAudioResponse
          .fromMap((map['playAudio'] as Map).cast<String, dynamic>()),
      telephonyTransferCall:
          GoogleCloudDialogflowCxV3beta1ResponseMessageTelephonyTransferCallResponse
              .fromMap((map['telephonyTransferCall'] as Map)
                  .cast<String, dynamic>()),
      text: GoogleCloudDialogflowCxV3beta1ResponseMessageTextResponse.fromMap(
          (map['text'] as Map).cast<String, dynamic>()),
    );
  }
}
