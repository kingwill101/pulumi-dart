import 'package:pulumi/pulumi.dart';
import 'disk_encryption_configuration_response.dart';
import 'disk_encryption_status_response.dart';
import 'instance_args24.dart';
import 'instance_failover_replica_response.dart';
import 'ip_mapping_response.dart';
import 'on_premises_configuration_response.dart';
import 'replica_configuration_response.dart';
import 'settings_response.dart';
import 'sql_out_of_disk_report_response.dart';
import 'sql_scheduled_maintenance_response.dart';
import 'ssl_cert_response.dart';

/// Creates a new Cloud SQL instance.
class Instance24 extends CustomResource {
  /// List all maintenance versions applicable on the instance
  late final Output<List<String>> availableMaintenanceVersions;

  /// The backend type. `SECOND_GEN`: Cloud SQL database instance. `EXTERNAL`: A database server that is not managed by Google. This property is read-only; use the `tier` property in the `settings` object to determine the database type.
  late final Output<String> backendType;

  /// Connection name of the Cloud SQL instance used in connection strings.
  late final Output<String> connectionName;

  /// The time when the instance was created in [RFC 3339](https://tools.ietf.org/html/rfc3339) format, for example `2012-11-15T16:19:00.094Z`.
  late final Output<String> createTime;

  /// The current disk usage of the instance in bytes. This property has been deprecated. Use the "cloudsql.googleapis.com/database/disk/bytes_used" metric in Cloud Monitoring API instead. Please see [this announcement](https://groups.google.com/d/msg/google-cloud-sql-announce/I_7-F9EBhT0/BtvFtdFeAgAJ) for details.
  late final Output<String> currentDiskSize;

  /// Stores the current database version running on the instance including minor version such as `MYSQL_8_0_18`.
  late final Output<String> databaseInstalledVersion;

  /// The database engine type and version. The `databaseVersion` field cannot be changed after instance creation.
  late final Output<String> databaseVersion;

  /// Disk encryption configuration specific to an instance.
  late final Output<DiskEncryptionConfigurationResponse>
      diskEncryptionConfiguration;

  /// Disk encryption status specific to an instance.
  late final Output<DiskEncryptionStatusResponse> diskEncryptionStatus;

  /// The dns name of the instance.
  late final Output<String> dnsName;

  /// This field is deprecated and will be removed from a future version of the API. Use the `settings.settingsVersion` field instead.
  late final Output<String> etag;

  /// The name and status of the failover replica.
  late final Output<InstanceFailoverReplicaResponse> failoverReplica;

  /// The Compute Engine zone that the instance is currently serving from. This value could be different from the zone that was specified when the instance was created if the instance has failed over to its secondary zone. WARNING: Changing this might restart the instance.
  late final Output<String> gceZone;

  /// The instance type.
  late final Output<String> instanceType;

  /// The assigned IP addresses for the instance.
  late final Output<List<IpMappingResponse>> ipAddresses;

  /// The IPv6 address assigned to the instance. (Deprecated) This property was applicable only to First Generation instances.
  late final Output<String> ipv6Address;

  /// This is always `sql#instance`.
  late final Output<String> kind;

  /// The current software version on the instance.
  late final Output<String> maintenanceVersion;

  /// The name of the instance which will act as primary in the replication setup.
  late final Output<String> masterInstanceName;

  /// The maximum disk size of the instance in bytes.
  late final Output<String> maxDiskSize;

  /// Name of the Cloud SQL instance. This does not include the project ID.
  late final Output<String> name;

  /// Configuration specific to on-premises instances.
  late final Output<OnPremisesConfigurationResponse> onPremisesConfiguration;

  /// This field represents the report generated by the proactive database wellness job for OutOfDisk issues. * Writers: * the proactive database wellness job for OOD. * Readers: * the proactive database wellness job
  late final Output<SqlOutOfDiskReportResponse> outOfDiskReport;

  /// DEPRECATED: please use write_endpoint instead.
  late final Output<String> primaryDnsName;
  late final Output<String> project;

  /// The link to service attachment of PSC instance.
  late final Output<String> pscServiceAttachmentLink;

  /// The geographical region. Can be: * `us-central` (`FIRST_GEN` instances only) * `us-central1` (`SECOND_GEN` instances only) * `asia-east1` or `europe-west1`. Defaults to `us-central` or `us-central1` depending on the instance type. The region cannot be changed after instance creation.
  late final Output<String> region;

  /// Configuration specific to failover replicas and read replicas.
  late final Output<ReplicaConfigurationResponse> replicaConfiguration;

  /// The replicas of the instance.
  late final Output<List<String>> replicaNames;

  /// Initial root password. Use only on creation. You must set root passwords before you can connect to PostgreSQL instances.
  late final Output<String> rootPassword;

  /// The status indicating if instance satisfiesPzs. Reserved for future use.
  late final Output<bool> satisfiesPzs;

  /// The start time of any upcoming scheduled maintenance for this instance.
  late final Output<SqlScheduledMaintenanceResponse> scheduledMaintenance;

  /// The Compute Engine zone that the failover instance is currently serving from for a regional instance. This value could be different from the zone that was specified when the instance was created if the instance has failed over to its secondary/failover zone.
  late final Output<String> secondaryGceZone;

  /// The URI of this resource.
  late final Output<String> selfLink;

  /// SSL configuration.
  late final Output<SslCertResponse> serverCaCert;

  /// The service account email address assigned to the instance.\This property is read-only.
  late final Output<String> serviceAccountEmailAddress;

  /// The user settings.
  late final Output<SettingsResponse> settings;
  late final Output<String> sqlNetworkArchitecture;

  /// The current serving state of the Cloud SQL instance.
  late final Output<String> state;

  /// If the instance state is SUSPENDED, the reason for the suspension.
  late final Output<List<String>> suspensionReason;

  /// The dns name of the primary instance in a replication group.
  late final Output<String> writeEndpoint;

  Instance24(
    String name, {
    InstanceArgs24? args,
    CustomResourceOptions? options,
  }) : super(
          'google-native:sqladmin/v1:Instance',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.availableMaintenanceVersions =
        registerOutput<List<String>>('availableMaintenanceVersions');
    this.backendType = registerOutput<String>('backendType');
    this.connectionName = registerOutput<String>('connectionName');
    this.createTime = registerOutput<String>('createTime');
    this.currentDiskSize = registerOutput<String>('currentDiskSize');
    this.databaseInstalledVersion =
        registerOutput<String>('databaseInstalledVersion');
    this.databaseVersion = registerOutput<String>('databaseVersion');
    this.diskEncryptionConfiguration =
        registerOutput<DiskEncryptionConfigurationResponse>(
            'diskEncryptionConfiguration');
    this.diskEncryptionStatus =
        registerOutput<DiskEncryptionStatusResponse>('diskEncryptionStatus');
    this.dnsName = registerOutput<String>('dnsName');
    this.etag = registerOutput<String>('etag');
    this.failoverReplica =
        registerOutput<InstanceFailoverReplicaResponse>('failoverReplica');
    this.gceZone = registerOutput<String>('gceZone');
    this.instanceType = registerOutput<String>('instanceType');
    this.ipAddresses = registerOutput<List<IpMappingResponse>>('ipAddresses');
    this.ipv6Address = registerOutput<String>('ipv6Address');
    this.kind = registerOutput<String>('kind');
    this.maintenanceVersion = registerOutput<String>('maintenanceVersion');
    this.masterInstanceName = registerOutput<String>('masterInstanceName');
    this.maxDiskSize = registerOutput<String>('maxDiskSize');
    this.name = registerOutput<String>('name');
    this.onPremisesConfiguration =
        registerOutput<OnPremisesConfigurationResponse>(
            'onPremisesConfiguration');
    this.outOfDiskReport =
        registerOutput<SqlOutOfDiskReportResponse>('outOfDiskReport');
    this.primaryDnsName = registerOutput<String>('primaryDnsName');
    this.project = registerOutput<String>('project');
    this.pscServiceAttachmentLink =
        registerOutput<String>('pscServiceAttachmentLink');
    this.region = registerOutput<String>('region');
    this.replicaConfiguration =
        registerOutput<ReplicaConfigurationResponse>('replicaConfiguration');
    this.replicaNames = registerOutput<List<String>>('replicaNames');
    this.rootPassword = registerOutput<String>('rootPassword');
    this.satisfiesPzs = registerOutput<bool>('satisfiesPzs');
    this.scheduledMaintenance =
        registerOutput<SqlScheduledMaintenanceResponse>('scheduledMaintenance');
    this.secondaryGceZone = registerOutput<String>('secondaryGceZone');
    this.selfLink = registerOutput<String>('selfLink');
    this.serverCaCert = registerOutput<SslCertResponse>('serverCaCert');
    this.serviceAccountEmailAddress =
        registerOutput<String>('serviceAccountEmailAddress');
    this.settings = registerOutput<SettingsResponse>('settings');
    this.sqlNetworkArchitecture =
        registerOutput<String>('sqlNetworkArchitecture');
    this.state = registerOutput<String>('state');
    this.suspensionReason = registerOutput<List<String>>('suspensionReason');
    this.writeEndpoint = registerOutput<String>('writeEndpoint');
  }
}
