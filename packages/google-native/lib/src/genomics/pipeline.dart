import 'package:pulumi/pulumi.dart' as pulumi;
import 'docker_executor_response.dart';
import 'pipeline_args.dart';
import 'pipeline_parameter_response.dart';
import 'pipeline_resources_response.dart';

/// Creates a pipeline that can be run later. Create takes a Pipeline that has all fields other than `pipelineId` populated, and then returns the same pipeline with `pipelineId` populated. This id can be used to run the pipeline. Caller must have WRITE permission to the project.
class Pipeline extends pulumi.CustomResource {
  /// User-specified description.
  late final pulumi.Output<String> description;

  /// Specifies the docker run information.
  late final pulumi.Output<DockerExecutorResponse> docker;

  /// Input parameters of the pipeline.
  late final pulumi.Output<List<PipelineParameterResponse>> inputParameters;

  /// A user specified pipeline name that does not have to be unique. This name can be used for filtering Pipelines in ListPipelines.
  late final pulumi.Output<String> name;

  /// Output parameters of the pipeline.
  late final pulumi.Output<List<PipelineParameterResponse>> outputParameters;

  /// Unique pipeline id that is generated by the service when CreatePipeline is called. Cannot be specified in the Pipeline used in the CreatePipelineRequest, and will be populated in the response to CreatePipeline and all subsequent Get and List calls. Indicates that the service has registered this pipeline.
  late final pulumi.Output<String> pipelineId;

  /// The project in which to create the pipeline. The caller must have WRITE access.
  late final pulumi.Output<String> project;

  /// Specifies resource requirements for the pipeline run. Required fields: * minimumCpuCores * minimumRamGb
  late final pulumi.Output<PipelineResourcesResponse> resources;

  /// Creates a new [Pipeline].
  /// [name] The Pulumi resource name.
  /// [args] Arguments used to configure this [Pipeline]. {@macro pulumi_genomics_v1alpha2_pipeline_args_doc}
  /// [options] Resource options controlling this resource's behavior.
  Pipeline(
    String name, {
    PipelineArgs? args,
    pulumi.CustomResourceOptions? options,
  }) : super(
          'google-native:genomics/v1alpha2:Pipeline',
          name,
          pulumi.Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? pulumi.CustomResourceOptions(),
        ) {
    this.description = registerOutput<String>('description');
    this.docker = registerOutput<DockerExecutorResponse>('docker');
    this.inputParameters =
        registerOutput<List<PipelineParameterResponse>>('inputParameters');
    this.name = registerOutput<String>('name');
    this.outputParameters =
        registerOutput<List<PipelineParameterResponse>>('outputParameters');
    this.pipelineId = registerOutput<String>('pipelineId');
    this.project = registerOutput<String>('project');
    this.resources = registerOutput<PipelineResourcesResponse>('resources');
  }
}
