/// Creates a Route resource in the specified project using the data included in the request.
class Route extends pulumi.CustomResource {
  /// Whether this route can conflict with existing subnetworks. Setting this to true allows this route to conflict with subnetworks that have already been configured on the corresponding network.
  late final pulumi.Output<bool> allowConflictingSubnetworks;

  /// AS path.
  late final pulumi.Output<List<RouteAsPathResponse>> asPaths;

  /// Creation timestamp in RFC3339 text format.
  late final pulumi.Output<String> creationTimestamp;

  /// An optional description of this resource. Provide this field when you create the resource.
  late final pulumi.Output<String> description;

  /// The destination range of outgoing packets that this route applies to. Both IPv4 and IPv6 are supported. Must specify an IPv4 range (e.g. 192.0.2.0/24) or an IPv6 range in RFC 4291 format (e.g. 2001:db8::/32). IPv6 range will be displayed using RFC 5952 compressed format.
  late final pulumi.Output<String> destRange;

  /// ILB route behavior when ILB is deemed unhealthy based on user specified threshold on the Backend Service of the internal load balancing.
  late final pulumi.Output<String> ilbRouteBehaviorOnUnhealthy;

  /// Type of this resource. Always compute#routes for Route resources.
  late final pulumi.Output<String> kind;

  /// Name of the resource. Provided by the client when the resource is created. The name must be 1-63 characters long, and comply with RFC1035. Specifically, the name must be 1-63 characters long and match the regular expression `[a-z]([-a-z0-9]*[a-z0-9])?`. The first character must be a lowercase letter, and all following characters (except for the last character) must be a dash, lowercase letter, or digit. The last character must be a lowercase letter or digit.
  late final pulumi.Output<String> name;

  /// Fully-qualified URL of the network that this route applies to.
  late final pulumi.Output<String> network;

  /// The URL to a gateway that should handle matching packets. You can only specify the internet gateway using a full or partial valid URL: projects/ project/global/gateways/default-internet-gateway
  late final pulumi.Output<String> nextHopGateway;

  /// The full resource name of the Network Connectivity Center hub that will handle matching packets.
  late final pulumi.Output<String> nextHopHub;

  /// The URL to a forwarding rule of type loadBalancingScheme=INTERNAL that should handle matching packets or the IP address of the forwarding Rule. For example, the following are all valid URLs: - 10.128.0.56 - https://www.googleapis.com/compute/v1/projects/project/regions/region /forwardingRules/forwardingRule - regions/region/forwardingRules/forwardingRule
  late final pulumi.Output<String> nextHopIlb;

  /// The URL to an instance that should handle matching packets. You can specify this as a full or partial URL. For example: https://www.googleapis.com/compute/v1/projects/project/zones/zone/instances/
  late final pulumi.Output<String> nextHopInstance;

  /// [Output only] Internal fixed region-to-region cost that Google Cloud calculates based on factors such as network performance, distance, and available bandwidth between regions.
  late final pulumi.Output<int> nextHopInterRegionCost;

  /// The URL to an InterconnectAttachment which is the next hop for the route. This field will only be populated for the dynamic routes generated by Cloud Router with a linked interconnectAttachment.
  late final pulumi.Output<String> nextHopInterconnectAttachment;

  /// The network IP address of an instance that should handle matching packets. Both IPv6 address and IPv4 addresses are supported. Must specify an IPv4 address in dot-decimal notation (e.g. 192.0.2.99) or an IPv6 address in RFC 4291 format (e.g. 2001:db8::2d9:51:0:0 or 2001:db8:0:0:2d9:51:0:0). IPv6 addresses will be displayed using RFC 5952 compressed format (e.g. 2001:db8::2d9:51:0:0). Should never be an IPv4-mapped IPv6 address.
  late final pulumi.Output<String> nextHopIp;

  /// Multi-Exit Discriminator, a BGP route metric that indicates the desirability of a particular route in a network.
  late final pulumi.Output<int> nextHopMed;

  /// The URL of the local network if it should handle matching packets.
  late final pulumi.Output<String> nextHopNetwork;

  /// Indicates the origin of the route. Can be IGP (Interior Gateway Protocol), EGP (Exterior Gateway Protocol), or INCOMPLETE.
  late final pulumi.Output<String> nextHopOrigin;

  /// The network peering name that should handle matching packets, which should conform to RFC1035.
  late final pulumi.Output<String> nextHopPeering;

  /// The URL to a VpnTunnel that should handle matching packets.
  late final pulumi.Output<String> nextHopVpnTunnel;

  /// The priority of this route. Priority is used to break ties in cases where there is more than one matching route of equal prefix length. In cases where multiple routes have equal prefix length, the one with the lowest-numbered priority value wins. The default value is `1000`. The priority value must be from `0` to `65535`, inclusive.
  late final pulumi.Output<int> priority;
  late final pulumi.Output<String> project;

  /// An optional request ID to identify requests. Specify a unique request ID so that if you must retry your request, the server will know to ignore the request if it has already been completed. For example, consider a situation where you make an initial request and the request times out. If you make the request again with the same request ID, the server can check if original operation with the same request ID was received, and if so, will ignore the second request. This prevents clients from accidentally creating duplicate commitments. The request ID must be a valid UUID with the exception that zero UUID is not supported ( 00000000-0000-0000-0000-000000000000).
  late final pulumi.Output<String?> requestId;

  /// [Output only] The status of the route.
  late final pulumi.Output<String> routeStatus;

  /// The type of this route, which can be one of the following values: - 'TRANSIT' for a transit route that this router learned from another Cloud Router and will readvertise to one of its BGP peers - 'SUBNET' for a route from a subnet of the VPC - 'BGP' for a route learned from a BGP peer of this router - 'STATIC' for a static route
  late final pulumi.Output<String> routeType;

  /// Server-defined fully-qualified URL for this resource.
  late final pulumi.Output<String> selfLink;

  /// Server-defined URL for this resource with the resource id.
  late final pulumi.Output<String> selfLinkWithId;

  /// A list of instance tags to which this route applies.
  late final pulumi.Output<List<String>> tags;

  /// If potential misconfigurations are detected for this route, this field will be populated with warning messages.
  late final pulumi.Output<List<RouteWarningsItemResponse>> warnings;

  /// Creates a new [Route].
  /// [name] The Pulumi resource name.
  /// [args] Arguments used to configure this [Route]. {@macro pulumi_compute_alpha_route_args_doc}
  /// [options] Resource options controlling this resource's behavior.
  Route(
    String name, {
    RouteArgs? args,
    pulumi.CustomResourceOptions? options,
  }) : super(
          'google-native:compute/alpha:Route',
          name,
          pulumi.Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? pulumi.CustomResourceOptions(),
        ) {
    this.allowConflictingSubnetworks =
        registerOutput<bool>('allowConflictingSubnetworks');
    this.asPaths = registerOutput<List<RouteAsPathResponse>>('asPaths');
    this.creationTimestamp = registerOutput<String>('creationTimestamp');
    this.description = registerOutput<String>('description');
    this.destRange = registerOutput<String>('destRange');
    this.ilbRouteBehaviorOnUnhealthy =
        registerOutput<String>('ilbRouteBehaviorOnUnhealthy');
    this.kind = registerOutput<String>('kind');
    this.name = registerOutput<String>('name');
    this.network = registerOutput<String>('network');
    this.nextHopGateway = registerOutput<String>('nextHopGateway');
    this.nextHopHub = registerOutput<String>('nextHopHub');
    this.nextHopIlb = registerOutput<String>('nextHopIlb');
    this.nextHopInstance = registerOutput<String>('nextHopInstance');
    this.nextHopInterRegionCost = registerOutput<int>('nextHopInterRegionCost');
    this.nextHopInterconnectAttachment =
        registerOutput<String>('nextHopInterconnectAttachment');
    this.nextHopIp = registerOutput<String>('nextHopIp');
    this.nextHopMed = registerOutput<int>('nextHopMed');
    this.nextHopNetwork = registerOutput<String>('nextHopNetwork');
    this.nextHopOrigin = registerOutput<String>('nextHopOrigin');
    this.nextHopPeering = registerOutput<String>('nextHopPeering');
    this.nextHopVpnTunnel = registerOutput<String>('nextHopVpnTunnel');
    this.priority = registerOutput<int>('priority');
    this.project = registerOutput<String>('project');
    this.requestId = registerOutput<String?>('requestId');
    this.routeStatus = registerOutput<String>('routeStatus');
    this.routeType = registerOutput<String>('routeType');
    this.selfLink = registerOutput<String>('selfLink');
    this.selfLinkWithId = registerOutput<String>('selfLinkWithId');
    this.tags = registerOutput<List<String>>('tags');
    this.warnings = registerOutput<List<RouteWarningsItemResponse>>('warnings');
  }
}
