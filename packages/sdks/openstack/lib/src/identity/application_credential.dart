/// Manages a V3 Application Credential resource within OpenStack Keystone.
///
/// &gt; **Note:** All arguments including the application credential name and secret
/// will be stored in the raw state as plain-text. Read more about sensitive data
/// in state.
///
/// &gt; **Note:** An Application Credential is created within the authenticated user
/// project scope and is not visible by an admin or other accounts.
/// The Application Credential visibility is similar to
/// `openstack.compute.Keypair`.
///
/// ## Example Usage
///
/// ### Predefined secret
///
/// Application credential below will have only one `swiftoperator` role.
///
///
/// ```typescript
/// import * as pulumi from "@pulumi/pulumi";
/// import * as openstack from "@pulumi/openstack";
///
/// const swift = new openstack.identity.ApplicationCredential("swift", {
///     name: "swift",
///     description: "Swift technical application credential",
///     secret: "supersecret",
///     roles: ["swiftoperator"],
///     expiresAt: "2019-02-13T12:12:12Z",
/// });
/// ```
/// ```python
/// import pulumi
/// import pulumi_openstack as openstack
///
/// swift = openstack.identity.ApplicationCredential("swift",
///     name="swift",
///     description="Swift technical application credential",
///     secret="supersecret",
///     roles=["swiftoperator"],
///     expires_at="2019-02-13T12:12:12Z")
/// ```
/// ```csharp
/// using System.Collections.Generic;
/// using System.Linq;
/// using Pulumi;
/// using OpenStack = Pulumi.OpenStack;
///
/// return await Deployment.RunAsync(() =>
/// {
///     var swift = new OpenStack.Identity.ApplicationCredential("swift", new()
///     {
///         Name = "swift",
///         Description = "Swift technical application credential",
///         Secret = "supersecret",
///         Roles = new[]
///         {
///             "swiftoperator",
///         },
///         ExpiresAt = "2019-02-13T12:12:12Z",
///     });
///
/// });
/// ```
