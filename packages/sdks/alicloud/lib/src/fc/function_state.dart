  /// [instanceConcurrency] The maximum number of requests can be executed concurrently within the single function instance.
  /// [instanceType] The instance type of the function.
  /// [lastModified] The date this resource was last modified.
  /// [layers] The configuration for layers.
  /// [memorySize] Amount of memory in MB your function can use at runtime. Defaults to `128`. Limits to [128, 32768].
  /// [name] The Function Compute function name. It is the only in one service and is conflict with "name_prefix".
  /// [namePrefix] Setting a prefix to get a only function name. It is conflict with "name".
  /// [ossBucket] The OSS bucket location containing the function's deployment package. Conflicts with `filename`. This bucket must reside in the same Alibaba Cloud region where you are creating the function.
  /// [ossKey] The OSS key of an object containing the function's deployment package. Conflicts with `filename`.
  /// [runtime] See [Runtimes][https://www.alibabacloud.com/help/zh/function-compute/latest/manage-functions#multiTask3514] for valid values.
  /// [service] The Function Compute service name.
  /// [timeout] The amount of time your function has to run in seconds.
  FunctionState({
    this.caPort,
    this.codeChecksum,
    this.customContainerConfig,
    this.description,
    this.environmentVariables,
    this.filename,
    this.functionArn,
    this.functionId,
