  /// [codeChecksum] The checksum (crc64) of the function code.Used to trigger updates.The value can be generated by data source alicloud_file_crc64_checksum.
  /// [customContainerConfig] The configuration for custom container runtime.See `custom_container_config` below.
  /// [description] The Function Compute function description.
  /// [environmentVariables] A map that defines environment variables for the function.
  /// [filename] The path to the function's deployment package within the local filesystem. It is conflict with the `oss_`-prefixed options.
  /// [functionArn] The Function Compute service function arn. It formats as `acs:fc:<region>:<uid>:services/<serviceName>.LATEST/functions/<functionName>`.
  /// [functionId] The Function Compute service function ID.
  /// [handler] The function [entry point](https://www.alibabacloud.com/help/doc-detail/157704.htm) in your code.
  /// [initializationTimeout] The maximum length of time, in seconds, that the function's initialization should be run for.
