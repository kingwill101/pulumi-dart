/// The minimum strength TLS cipher suite allowed for an application
enum TlsCipherSuites {
  valueTLSAES256GCMSHA384("TLS_AES_256_GCM_SHA384"),
  valueTLSAES128GCMSHA256("TLS_AES_128_GCM_SHA256"),
  valueTLSECDHEECDSAWITHAES256GCMSHA384(
    "TLS_ECDHE_ECDSA_WITH_AES_256_GCM_SHA384",
  ),
  valueTLSECDHEECDSAWITHAES128CBCSHA256(
    "TLS_ECDHE_ECDSA_WITH_AES_128_CBC_SHA256",
  ),
  valueTLSECDHEECDSAWITHAES128GCMSHA256(
    "TLS_ECDHE_ECDSA_WITH_AES_128_GCM_SHA256",
  ),
  valueTLSECDHERSAWITHAES256GCMSHA384("TLS_ECDHE_RSA_WITH_AES_256_GCM_SHA384"),
  valueTLSECDHERSAWITHAES128GCMSHA256("TLS_ECDHE_RSA_WITH_AES_128_GCM_SHA256"),
  valueTLSECDHERSAWITHAES256CBCSHA384("TLS_ECDHE_RSA_WITH_AES_256_CBC_SHA384"),
  valueTLSECDHERSAWITHAES128CBCSHA256("TLS_ECDHE_RSA_WITH_AES_128_CBC_SHA256"),
  valueTLSECDHERSAWITHAES256CBCSHA("TLS_ECDHE_RSA_WITH_AES_256_CBC_SHA"),
  valueTLSECDHERSAWITHAES128CBCSHA("TLS_ECDHE_RSA_WITH_AES_128_CBC_SHA"),
  valueTLSRSAWITHAES256GCMSHA384("TLS_RSA_WITH_AES_256_GCM_SHA384"),
  valueTLSRSAWITHAES128GCMSHA256("TLS_RSA_WITH_AES_128_GCM_SHA256"),
  valueTLSRSAWITHAES256CBCSHA256("TLS_RSA_WITH_AES_256_CBC_SHA256"),
  valueTLSRSAWITHAES128CBCSHA256("TLS_RSA_WITH_AES_128_CBC_SHA256"),
  valueTLSRSAWITHAES256CBCSHA("TLS_RSA_WITH_AES_256_CBC_SHA"),
  valueTLSRSAWITHAES128CBCSHA("TLS_RSA_WITH_AES_128_CBC_SHA");

  const TlsCipherSuites(this.wireValue);
  final String wireValue;

  static TlsCipherSuites fromValue(String value) {
    for (final item in TlsCipherSuites.values) {
      if (item.wireValue == value) {
        return item;
      }
    }
    throw ArgumentError('Unknown TlsCipherSuites value: $value');
  }
}
