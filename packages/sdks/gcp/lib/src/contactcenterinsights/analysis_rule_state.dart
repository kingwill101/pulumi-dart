// ignore_for_file: unused_element, unnecessary_cast

import 'package:pulumi/pulumi.dart' as pulumi;
import 'analysis_rule_annotator_selector.dart';

/// Input properties used for looking up and filtering AnalysisRule resources.
class AnalysisRuleState {
  /// If true, apply this rule to conversations. Otherwise, this rule is
  /// inactive and saved as a draft.
  final pulumi.Input<bool>? active;
  /// Percentage of conversations that we should apply this analysis setting
  /// automatically, between [0, 1]. For example, 0.1 means 10%. Conversations
  /// are sampled in a determenestic way. The original runtime_percentage &
  /// upload percentage will be replaced by defining filters on the conversation.
  final pulumi.Input<double>? analysisPercentage;
  /// Selector of all available annotators and phrase matchers to run.
  /// Structure is documented below.
  final pulumi.Input<AnalysisRuleAnnotatorSelector>? annotatorSelector;
  /// Filter for the conversations that should apply this analysis
  /// rule. An empty filter means this analysis rule applies to all
  /// conversations.
  /// Refer to https://cloud.google.com/contact-center/insights/docs/filtering
  /// for details.
  final pulumi.Input<String>? conversationFilter;
  /// Output only. The time at which this analysis rule was created.
  final pulumi.Input<String>? createTime;
  /// Display Name of the analysis rule.
  final pulumi.Input<String>? displayName;
  /// Location of the resource.
  final pulumi.Input<String>? location;
  /// The resource name of the analysis rule. Randomly generated by Insights.
  final pulumi.Input<String>? name;
  /// The ID of the project in which the resource belongs.
  /// If it is not provided, the provider project is used.
  final pulumi.Input<String>? project;
  /// Output only. The most recent time at which this analysis rule was updated.
  final pulumi.Input<String>? updateTime;

  /// Creates a new [AnalysisRuleState].
  /// [active] If true, apply this rule to conversations. Otherwise, this rule is
  /// [analysisPercentage] Percentage of conversations that we should apply this analysis setting
  /// [annotatorSelector] Selector of all available annotators and phrase matchers to run.
  /// [conversationFilter] Filter for the conversations that should apply this analysis
  /// [createTime] Output only. The time at which this analysis rule was created.
  /// [displayName] Display Name of the analysis rule.
  /// [location] Location of the resource.
  /// [name] The resource name of the analysis rule. Randomly generated by Insights.
  /// [project] The ID of the project in which the resource belongs.
  /// [updateTime] Output only. The most recent time at which this analysis rule was updated.
  AnalysisRuleState({
    this.active,
    this.analysisPercentage,
    this.annotatorSelector,
    this.conversationFilter,
    this.createTime,
    this.displayName,
    this.location,
    this.name,
    this.project,
    this.updateTime,
  });

  Map<String, dynamic> toMap() {
    return <String, dynamic>{
      'active': ?active,
      'analysisPercentage': ?analysisPercentage,
      'annotatorSelector': ?pulumi.Input.mapOptionalInputValue<AnalysisRuleAnnotatorSelector, Map<String, dynamic>>(annotatorSelector, (value) => value.toMap()),
      'conversationFilter': ?conversationFilter,
      'createTime': ?createTime,
      'displayName': ?displayName,
      'location': ?location,
      'name': ?name,
      'project': ?project,
      'updateTime': ?updateTime,
    };
  }

  factory AnalysisRuleState.fromMap(Map<String, dynamic> map) {
    return AnalysisRuleState(
      active: map['active'] == null ? null : (map['active']! as bool).input(),
      analysisPercentage: map['analysisPercentage'] == null ? null : (map['analysisPercentage']! as double).input(),
      annotatorSelector: map['annotatorSelector'] == null ? null : (AnalysisRuleAnnotatorSelector.fromMap((map['annotatorSelector']! as Map).cast<String, dynamic>())).input(),
      conversationFilter: map['conversationFilter'] == null ? null : (map['conversationFilter']! as String).input(),
      createTime: map['createTime'] == null ? null : (map['createTime']! as String).input(),
      displayName: map['displayName'] == null ? null : (map['displayName']! as String).input(),
      location: map['location'] == null ? null : (map['location']! as String).input(),
      name: map['name'] == null ? null : (map['name']! as String).input(),
      project: map['project'] == null ? null : (map['project']! as String).input(),
      updateTime: map['updateTime'] == null ? null : (map['updateTime']! as String).input(),
    );
  }
}

