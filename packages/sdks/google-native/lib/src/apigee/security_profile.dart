import 'package:pulumi/pulumi.dart' as pulumi;
import 'google_cloud_apigee_v1_profile_config_response.dart';
import 'security_profile_args.dart';

/// CreateSecurityProfile create a new custom security profile.
class SecurityProfile extends pulumi.CustomResource {
  /// Description of the security profile.
  late final pulumi.Output<String> description;

  /// Display name of the security profile.
  late final pulumi.Output<String> displayName;

  /// List of environments attached to security profile.
  late final pulumi.Output<List<Map<String, dynamic>>> environments;

  /// Maximum security score that can be generated by this profile.
  late final pulumi.Output<int> maxScore;

  /// Minimum security score that can be generated by this profile.
  late final pulumi.Output<int> minScore;

  /// Immutable. Name of the security profile resource. Format: organizations/{org}/securityProfiles/{profile}
  late final pulumi.Output<String> name;
  late final pulumi.Output<String> organizationId;

  /// Customized profile configuration that computes the security score.
  late final pulumi.Output<GoogleCloudApigeeV1ProfileConfigResponse>
  profileConfig;

  /// The time when revision was created.
  late final pulumi.Output<String> revisionCreateTime;

  /// Revision ID of the security profile.
  late final pulumi.Output<String> revisionId;

  /// The time when revision was published. Once published, the security profile revision cannot be updated further and can be attached to environments.
  late final pulumi.Output<String> revisionPublishTime;

  /// The time when revision was updated.
  late final pulumi.Output<String> revisionUpdateTime;

  /// List of profile scoring configs in this revision.
  late final pulumi.Output<List<Map<String, dynamic>>> scoringConfigs;

  /// Required. The ID to use for the SecurityProfile, which will become the final component of the action's resource name. This value should be 1-63 characters and validated by "(^[a-z]([a-z0-9-]{0,61}[a-z0-9])?$)".
  late final pulumi.Output<String> securityProfileId;

  /// Creates a new [SecurityProfile].
  /// [name] The Pulumi resource name.
  /// [args] Arguments used to configure this [SecurityProfile]. {@macro pulumi_apigee_v1_security_profile_args_doc}
  /// [options] Resource options controlling this resource's behavior.
  SecurityProfile(
    String name, {
    SecurityProfileArgs? args,
    pulumi.CustomResourceOptions? options,
  }) : super(
         'google-native:apigee/v1:SecurityProfile',
         name,
         pulumi.Input.mapToInputs(args?.toMap() ?? const {}),
         options ?? pulumi.CustomResourceOptions(),
       ) {
    description = registerOutput<String>('description');
    displayName = registerOutput<String>('displayName');
    environments = registerOutput<List<Map<String, dynamic>>>('environments');
    maxScore = registerOutput<int>('maxScore');
    minScore = registerOutput<int>('minScore');
    this.name = registerOutput<String>('name');
    organizationId = registerOutput<String>('organizationId');
    profileConfig = registerOutput<GoogleCloudApigeeV1ProfileConfigResponse>(
      'profileConfig',
      decoder: (raw) {
        final guardedValue = raw;
        if (guardedValue == null) return null;
        return GoogleCloudApigeeV1ProfileConfigResponse.fromMap(
          (guardedValue as Map).cast<String, dynamic>(),
        );
      },
    );
    revisionCreateTime = registerOutput<String>('revisionCreateTime');
    revisionId = registerOutput<String>('revisionId');
    revisionPublishTime = registerOutput<String>('revisionPublishTime');
    revisionUpdateTime = registerOutput<String>('revisionUpdateTime');
    scoringConfigs = registerOutput<List<Map<String, dynamic>>>(
      'scoringConfigs',
    );
    securityProfileId = registerOutput<String>('securityProfileId');
  }
}
