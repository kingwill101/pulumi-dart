import 'package:pulumi/pulumi.dart' as pulumi;
import 'api_args.dart';
import 'google_cloud_apigee_v1_entity_metadata_response.dart';

/// Creates an API proxy. The API proxy created will not be accessible at runtime until it is deployed to an environment. Create a new API proxy by setting the `name` query parameter to the name of the API proxy. Import an API proxy configuration bundle stored in zip format on your local machine to your organization by doing the following: * Set the `name` query parameter to the name of the API proxy. * Set the `action` query parameter to `import`. * Set the `Content-Type` header to `multipart/form-data`. * Pass as a file the name of API proxy configuration bundle stored in zip format on your local machine using the `file` form field. **Note**: To validate the API proxy configuration bundle only without importing it, set the `action` query parameter to `validate`. When importing an API proxy configuration bundle, if the API proxy does not exist, it will be created. If the API proxy exists, then a new revision is created. Invalid API proxy configurations are rejected, and a list of validation errors is returned to the client.
class Api extends pulumi.CustomResource {
  /// Action to perform when importing an API proxy configuration bundle. Set this parameter to one of the following values: * `import` to import the API proxy configuration bundle. * `validate` to validate the API proxy configuration bundle without importing it.
  late final pulumi.Output<String?> action;

  /// The type of the API proxy.
  late final pulumi.Output<String> apiProxyType;

  /// User labels applied to this API Proxy.
  late final pulumi.Output<Map<String, String>> labels;

  /// The id of the most recently created revision for this api proxy.
  late final pulumi.Output<String> latestRevisionId;

  /// Metadata describing the API proxy.
  late final pulumi.Output<GoogleCloudApigeeV1EntityMetadataResponse> metaData;

  /// Name of the API proxy. Restrict the characters used to: A-Za-z0-9._-
  late final pulumi.Output<String> name;
  late final pulumi.Output<String> organizationId;

  /// Whether this proxy is read-only. A read-only proxy cannot have new revisions created through calls to CreateApiProxyRevision. A proxy is read-only if it was generated by an archive.
  late final pulumi.Output<bool> readOnly;

  /// List of revisions defined for the API proxy.
  late final pulumi.Output<List<String>> revision;

  /// Ignored. All uploads are validated regardless of the value of this field. Maintained for compatibility with Apigee Edge API.
  late final pulumi.Output<bool?> validate;

  /// Creates a new [Api].
  /// [name] The Pulumi resource name.
  /// [args] Arguments used to configure this [Api]. {@macro pulumi_apigee_v1_api_args_doc}
  /// [options] Resource options controlling this resource's behavior.
  Api(String name, {ApiArgs? args, pulumi.CustomResourceOptions? options})
    : super(
        'google-native:apigee/v1:Api',
        name,
        pulumi.Input.mapToInputs(args?.toMap() ?? const {}),
        options ?? pulumi.CustomResourceOptions(),
      ) {
    action = registerOutput<String?>('action');
    apiProxyType = registerOutput<String>('apiProxyType');
    labels = registerOutput<Map<String, String>>('labels');
    latestRevisionId = registerOutput<String>('latestRevisionId');
    metaData = registerOutput<GoogleCloudApigeeV1EntityMetadataResponse>(
      'metaData',
    );
    this.name = registerOutput<String>('name');
    organizationId = registerOutput<String>('organizationId');
    readOnly = registerOutput<bool>('readOnly');
    revision = registerOutput<List<String>>('revision');
    validate = registerOutput<bool?>('validate');
  }
}
