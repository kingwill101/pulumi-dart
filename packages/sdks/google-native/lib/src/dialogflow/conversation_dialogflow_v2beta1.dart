import 'package:pulumi/pulumi.dart' as pulumi;
import 'conversation_dialogflow_v2beta1_args.dart';
import 'google_cloud_dialogflow_v2beta1_conversation_phone_number_response.dart';

/// Creates a new conversation. Conversations are auto-completed after 24 hours. Conversation Lifecycle: There are two stages during a conversation: Automated Agent Stage and Assist Stage. For Automated Agent Stage, there will be a dialogflow agent responding to user queries. For Assist Stage, there's no dialogflow agent responding to user queries. But we will provide suggestions which are generated from conversation. If Conversation.conversation_profile is configured for a dialogflow agent, conversation will start from `Automated Agent Stage`, otherwise, it will start from `Assist Stage`. And during `Automated Agent Stage`, once an Intent with Intent.live_agent_handoff is triggered, conversation will transfer to Assist Stage.
/// Auto-naming is currently not supported for this resource.
/// Note - this resource's API doesn't support deletion. When deleted, the resource will persist
/// on Google Cloud even though it will be deleted from Pulumi state.
class ConversationDialogflowV2beta1 extends pulumi.CustomResource {
  /// Optional. Identifier of the conversation. Generally it's auto generated by Google. Only set it if you cannot wait for the response to return a auto-generated one to you. The conversation ID must be compliant with the regression fomula `a-zA-Z*` with the characters length in range of [3,64]. If the field is provided, the caller is resposible for 1. the uniqueness of the ID, otherwise the request will be rejected. 2. the consistency for whether to use custom ID or not under a project to better ensure uniqueness.
  late final pulumi.Output<String?> conversationId;

  /// The Conversation Profile to be used to configure this Conversation. This field cannot be updated. Format: `projects//locations//conversationProfiles/`.
  late final pulumi.Output<String> conversationProfile;

  /// The stage of a conversation. It indicates whether the virtual agent or a human agent is handling the conversation. If the conversation is created with the conversation profile that has Dialogflow config set, defaults to ConversationStage.VIRTUAL_AGENT_STAGE; Otherwise, defaults to ConversationStage.HUMAN_ASSIST_STAGE. If the conversation is created with the conversation profile that has Dialogflow config set but explicitly sets conversation_stage to ConversationStage.HUMAN_ASSIST_STAGE, it skips ConversationStage.VIRTUAL_AGENT_STAGE stage and directly goes to ConversationStage.HUMAN_ASSIST_STAGE.
  late final pulumi.Output<String> conversationStage;

  /// The time the conversation was finished.
  late final pulumi.Output<String> endTime;

  /// The current state of the Conversation.
  late final pulumi.Output<String> lifecycleState;
  late final pulumi.Output<String> location;

  /// The unique identifier of this conversation. Format: `projects//locations//conversations/`.
  late final pulumi.Output<String> name;

  /// Required if the conversation is to be connected over telephony.
  late final pulumi.Output<
    GoogleCloudDialogflowV2beta1ConversationPhoneNumberResponse
  >
  phoneNumber;
  late final pulumi.Output<String> project;

  /// The time the conversation was started.
  late final pulumi.Output<String> startTime;

  /// Creates a new [ConversationDialogflowV2beta1].
  /// [name] The Pulumi resource name.
  /// [args] Arguments used to configure this [ConversationDialogflowV2beta1]. {@macro pulumi_dialogflow_v2beta1_conversation_dialogflow_v2beta1_args_doc}
  /// [options] Resource options controlling this resource's behavior.
  ConversationDialogflowV2beta1(
    String name, {
    ConversationDialogflowV2beta1Args? args,
    pulumi.CustomResourceOptions? options,
  }) : super(
         'google-native:dialogflow/v2beta1:Conversation',
         name,
         pulumi.Input.mapToInputs(args?.toMap() ?? const {}),
         options ?? pulumi.CustomResourceOptions(),
       ) {
    conversationId = registerOutput<String?>('conversationId');
    conversationProfile = registerOutput<String>('conversationProfile');
    conversationStage = registerOutput<String>('conversationStage');
    endTime = registerOutput<String>('endTime');
    lifecycleState = registerOutput<String>('lifecycleState');
    location = registerOutput<String>('location');
    this.name = registerOutput<String>('name');
    phoneNumber =
        registerOutput<
          GoogleCloudDialogflowV2beta1ConversationPhoneNumberResponse
        >('phoneNumber');
    project = registerOutput<String>('project');
    startTime = registerOutput<String>('startTime');
  }
}
