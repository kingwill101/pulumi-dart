import 'package:pulumi/pulumi.dart' as pulumi;
import 'execution_args.dart';
import 'execution_template_response.dart';

/// Creates a new Execution in a given project and location.
/// Auto-naming is currently not supported for this resource.
class Execution extends pulumi.CustomResource {
  /// Time the Execution was instantiated.
  late final pulumi.Output<String> createTime;

  /// A brief description of this execution.
  late final pulumi.Output<String> description;

  /// Name used for UI purposes. Name can only contain alphanumeric characters and underscores '_'.
  late final pulumi.Output<String> displayName;

  /// Required. User-defined unique ID of this execution.
  late final pulumi.Output<String> executionId;

  /// execute metadata including name, hardware spec, region, labels, etc.
  late final pulumi.Output<ExecutionTemplateResponse> executionTemplate;

  /// The URI of the external job used to execute the notebook.
  late final pulumi.Output<String> jobUri;
  late final pulumi.Output<String> location;

  /// The resource name of the execute. Format: `projects/{project_id}/locations/{location}/executions/{execution_id}`
  late final pulumi.Output<String> name;

  /// Output notebook file generated by this execution
  late final pulumi.Output<String> outputNotebookFile;
  late final pulumi.Output<String> project;

  /// State of the underlying AI Platform job.
  late final pulumi.Output<String> state;

  /// Time the Execution was last updated.
  late final pulumi.Output<String> updateTime;

  /// Creates a new [Execution].
  /// [name] The Pulumi resource name.
  /// [args] Arguments used to configure this [Execution]. {@macro pulumi_notebooks_v1_execution_args_doc}
  /// [options] Resource options controlling this resource's behavior.
  Execution(
    String name, {
    ExecutionArgs? args,
    pulumi.CustomResourceOptions? options,
  }) : super(
         'google-native:notebooks/v1:Execution',
         name,
         pulumi.Input.mapToInputs(args?.toMap() ?? const {}),
         options ?? pulumi.CustomResourceOptions(),
       ) {
    createTime = registerOutput<String>('createTime');
    description = registerOutput<String>('description');
    displayName = registerOutput<String>('displayName');
    executionId = registerOutput<String>('executionId');
    executionTemplate = registerOutput<ExecutionTemplateResponse>(
      'executionTemplate',
    );
    jobUri = registerOutput<String>('jobUri');
    location = registerOutput<String>('location');
    this.name = registerOutput<String>('name');
    outputNotebookFile = registerOutput<String>('outputNotebookFile');
    project = registerOutput<String>('project');
    state = registerOutput<String>('state');
    updateTime = registerOutput<String>('updateTime');
  }
}
