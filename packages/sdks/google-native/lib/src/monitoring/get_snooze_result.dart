// ignore_for_file: unused_element, unnecessary_cast

import 'criteria_response.dart';
import 'time_interval_response.dart';

/// Result data returned by getSnooze.
class GetSnoozeResult {
  /// This defines the criteria for applying the Snooze. See Criteria for more information.
  final CriteriaResponse criteria;
  /// A display name for the Snooze. This can be, at most, 512 unicode characters.
  final String displayName;
  /// The Snooze will be active from interval.start_time through interval.end_time. interval.start_time cannot be in the past. There is a 15 second clock skew to account for the time it takes for a request to reach the API from the UI.
  final TimeIntervalResponse interval;
  /// The name of the Snooze. The format is: projects/[PROJECT_ID_OR_NUMBER]/snoozes/[SNOOZE_ID] The ID of the Snooze will be generated by the system.
  final String name;

  /// Creates a new [GetSnoozeResult].
  /// [criteria] This defines the criteria for applying the Snooze. See Criteria for more information.
  /// [displayName] A display name for the Snooze. This can be, at most, 512 unicode characters.
  /// [interval] The Snooze will be active from interval.start_time through interval.end_time. interval.start_time cannot be in the past. There is a 15 second clock skew to account for the time it takes for a request to reach the API from the UI.
  /// [name] The name of the Snooze. The format is: projects/[PROJECT_ID_OR_NUMBER]/snoozes/[SNOOZE_ID] The ID of the Snooze will be generated by the system.
  GetSnoozeResult({
    required this.criteria,
    required this.displayName,
    required this.interval,
    required this.name,
  });

  Map<String, dynamic> toMap() {
    return <String, dynamic>{
      'criteria': criteria.toMap(),
      'displayName': displayName,
      'interval': interval.toMap(),
      'name': name,
    };
  }

  factory GetSnoozeResult.fromMap(Map<String, dynamic> map) {
    return GetSnoozeResult(
      criteria: CriteriaResponse.fromMap((map['criteria']! as Map).cast<String, dynamic>()),
      displayName: map['displayName'] as String,
      interval: TimeIntervalResponse.fromMap((map['interval']! as Map).cast<String, dynamic>()),
      name: map['name'] as String,
    );
  }
}

