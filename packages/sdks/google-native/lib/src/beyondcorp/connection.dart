import 'package:pulumi/pulumi.dart' as pulumi;
import 'application_endpoint_response.dart';
import 'connection_args.dart';
import 'gateway_response.dart';

/// Creates a new Connection in a given project and location.
class Connection extends pulumi.CustomResource {
  /// Address of the remote application endpoint for the BeyondCorp Connection.
  late final pulumi.Output<ApplicationEndpointResponse> applicationEndpoint;

  /// Optional. User-settable connection resource ID. * Must start with a letter. * Must contain between 4-63 characters from `/a-z-/`. * Must end with a number or a letter.
  late final pulumi.Output<String?> connectionId;

  /// Optional. List of [google.cloud.beyondcorp.v1main.Connector.name] that are authorised to be associated with this Connection.
  late final pulumi.Output<List<String>> connectors;

  /// Timestamp when the resource was created.
  late final pulumi.Output<String> createTime;

  /// Optional. An arbitrary user-provided name for the connection. Cannot exceed 64 characters.
  late final pulumi.Output<String> displayName;

  /// Optional. Gateway used by the connection.
  late final pulumi.Output<GatewayResponse> gateway;

  /// Optional. Resource labels to represent user provided metadata.
  late final pulumi.Output<Map<String, String>> labels;
  late final pulumi.Output<String> location;

  /// Unique resource name of the connection. The name is ignored when creating a connection.
  late final pulumi.Output<String> name;
  late final pulumi.Output<String> project;

  /// Optional. An optional request ID to identify requests. Specify a unique request ID so that if you must retry your request, the server will know to ignore the request if it has already been completed. The server will guarantee that for at least 60 minutes since the first request. For example, consider a situation where you make an initial request and the request times out. If you make the request again with the same request ID, the server can check if original operation with the same request ID was received, and if so, will ignore the second request. This prevents clients from accidentally creating duplicate commitments. The request ID must be a valid UUID with the exception that zero UUID is not supported (00000000-0000-0000-0000-000000000000).
  late final pulumi.Output<String?> requestId;

  /// The current state of the connection.
  late final pulumi.Output<String> state;

  /// The type of network connectivity used by the connection.
  late final pulumi.Output<String> type;

  /// A unique identifier for the instance generated by the system.
  late final pulumi.Output<String> uid;

  /// Timestamp when the resource was last modified.
  late final pulumi.Output<String> updateTime;

  /// Creates a new [Connection].
  /// [name] The Pulumi resource name.
  /// [args] Arguments used to configure this [Connection]. {@macro pulumi_beyondcorp_v1alpha_connection_args_doc}
  /// [options] Resource options controlling this resource's behavior.
  Connection(
    String name, {
    ConnectionArgs? args,
    pulumi.CustomResourceOptions? options,
  }) : super(
         'google-native:beyondcorp/v1alpha:Connection',
         name,
         pulumi.Input.mapToInputs(args?.toMap() ?? const {}),
         options ?? pulumi.CustomResourceOptions(),
       ) {
    applicationEndpoint = registerOutput<ApplicationEndpointResponse>(
      'applicationEndpoint',
      decoder: (raw) {
        final guardedValue = raw;
        if (guardedValue == null) return null;
        return ApplicationEndpointResponse.fromMap(
          (guardedValue as Map).cast<String, dynamic>(),
        );
      },
    );
    connectionId = registerOutput<String?>('connectionId');
    connectors = registerOutput<List<String>>('connectors');
    createTime = registerOutput<String>('createTime');
    displayName = registerOutput<String>('displayName');
    gateway = registerOutput<GatewayResponse>(
      'gateway',
      decoder: (raw) {
        final guardedValue = raw;
        if (guardedValue == null) return null;
        return GatewayResponse.fromMap(
          (guardedValue as Map).cast<String, dynamic>(),
        );
      },
    );
    labels = registerOutput<Map<String, String>>('labels');
    location = registerOutput<String>('location');
    this.name = registerOutput<String>('name');
    project = registerOutput<String>('project');
    requestId = registerOutput<String?>('requestId');
    state = registerOutput<String>('state');
    type = registerOutput<String>('type');
    uid = registerOutput<String>('uid');
    updateTime = registerOutput<String>('updateTime');
  }
}
