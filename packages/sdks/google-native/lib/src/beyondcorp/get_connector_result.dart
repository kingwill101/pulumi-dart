import 'principal_info_response.dart';
import 'resource_info_response.dart';

/// Result data returned by getConnector.
class GetConnectorResult {
  /// Timestamp when the resource was created.
  final String createTime;
  /// Optional. An arbitrary user-provided name for the connector. Cannot exceed 64 characters.
  final String displayName;
  /// Optional. Resource labels to represent user provided metadata.
  final Map<String, String> labels;
  /// Unique resource name of the connector. The name is ignored when creating a connector.
  final String name;
  /// Principal information about the Identity of the connector.
  final PrincipalInfoResponse principalInfo;
  /// Optional. Resource info of the connector.
  final ResourceInfoResponse resourceInfo;
  /// The current state of the connector.
  final String state;
  /// A unique identifier for the instance generated by the system.
  final String uid;
  /// Timestamp when the resource was last modified.
  final String updateTime;

  /// Creates a new [GetConnectorResult].
  /// [createTime] Timestamp when the resource was created.
  /// [displayName] Optional. An arbitrary user-provided name for the connector. Cannot exceed 64 characters.
  /// [labels] Optional. Resource labels to represent user provided metadata.
  /// [name] Unique resource name of the connector. The name is ignored when creating a connector.
  /// [principalInfo] Principal information about the Identity of the connector.
  /// [resourceInfo] Optional. Resource info of the connector.
  /// [state] The current state of the connector.
  /// [uid] A unique identifier for the instance generated by the system.
  /// [updateTime] Timestamp when the resource was last modified.
  const GetConnectorResult({
    required this.createTime,
    required this.displayName,
    required this.labels,
    required this.name,
    required this.principalInfo,
    required this.resourceInfo,
    required this.state,
    required this.uid,
    required this.updateTime,
  });

  Map<String, dynamic> toMap() {
    return <String, dynamic>{
      'createTime': createTime,
      'displayName': displayName,
      'labels': labels,
      'name': name,
      'principalInfo': principalInfo.toMap(),
      'resourceInfo': resourceInfo.toMap(),
      'state': state,
      'uid': uid,
      'updateTime': updateTime,
    };
  }

  factory GetConnectorResult.fromMap(Map<String, dynamic> map) {
    return GetConnectorResult(
      createTime: map['createTime'] as String,
      displayName: map['displayName'] as String,
      labels: (map['labels'] as Map).cast<String, String>(),
      name: map['name'] as String,
      principalInfo: PrincipalInfoResponse.fromMap((map['principalInfo']! as Map).cast<String, dynamic>()),
      resourceInfo: ResourceInfoResponse.fromMap((map['resourceInfo']! as Map).cast<String, dynamic>()),
      state: map['state'] as String,
      uid: map['uid'] as String,
      updateTime: map['updateTime'] as String,
    );
  }
}
