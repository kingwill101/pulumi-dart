/// &gt; If the managed resource supports a write-only attribute for the private key (first introduced in Terraform 1.11), then the ephemeral variant of `tls.PrivateKey` should be used, when possible, to avoid storing the private key data in the plan or state file.
///
/// Creates a PEM (and OpenSSH) formatted private key.
///
/// Generates a secure private key and encodes it in [PEM (RFC 1421)](https://datatracker.ietf.org/doc/html/rfc1421) and [OpenSSH PEM (RFC 4716)](https://datatracker.ietf.org/doc/html/rfc4716) formats. This resource is primarily intended for easily bootstrapping throwaway development environments.
///
/// &gt; **Security Notice** The private key generated by this resource will
/// be stored *unencrypted* in your Terraform state file. **Use of this resource
/// for production deployments is *not* recommended**. Instead, generate
/// a private key file outside of Terraform and distribute it securely
/// to the system where Terraform will be run.
///
/// This is a *logical resource*, so it contributes only to the current Terraform
/// state and does not create any external managed resources.
///
///
/// ## Example Usage
///
///
/// ```typescript
/// import * as pulumi from "@pulumi/pulumi";
/// import * as tls from "@pulumi/tls";
///
/// // ECDSA key with P384 elliptic curve
/// const ecdsa_p384_example = new tls.PrivateKey("ecdsa-p384-example", {
///     algorithm: "ECDSA",
///     ecdsaCurve: "P384",
/// });
/// // RSA key of size 4096 bits
/// const rsa_4096_example = new tls.PrivateKey("rsa-4096-example", {
///     algorithm: "RSA",
///     rsaBits: 4096,
/// });
/// // ED25519 key
/// const ed25519_example = new tls.PrivateKey("ed25519-example", {algorithm: "ED25519"});
/// ```
/// ```python
/// import pulumi
/// import pulumi_tls as tls
///
/// # ECDSA key with P384 elliptic curve
/// ecdsa_p384_example = tls.PrivateKey("ecdsa-p384-example",
///     algorithm="ECDSA",
///     ecdsa_curve="P384")
/// # RSA key of size 4096 bits
/// rsa_4096_example = tls.PrivateKey("rsa-4096-example",
///     algorithm="RSA",
///     rsa_bits=4096)
/// # ED25519 key
/// ed25519_example = tls.PrivateKey("ed25519-example", algorithm="ED25519")
