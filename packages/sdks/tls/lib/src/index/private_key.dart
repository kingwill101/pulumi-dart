///     });
///
///     // RSA key of size 4096 bits
///     var rsa_4096_example = new Tls.PrivateKey("rsa-4096-example", new()
///     {
///         Algorithm = "RSA",
///         RsaBits = 4096,
///     });
///
///     // ED25519 key
///     var ed25519_example = new Tls.PrivateKey("ed25519-example", new()
///     {
///         Algorithm = "ED25519",
///     });
///
/// });
/// ```
/// ```go
