import 'package:pulumi/pulumi.dart' as pulumi;
import 'custom_vcsintegration_args.dart';

/// Creates a new custom VCS integration for an organization. Custom VCS integrations allow connecting self-hosted or third-party version control systems (e.g. Gitea, Forgejo, Bitbucket Server) to Pulumi Deployments. Credentials are managed via ESC environments, and deployments are triggered by inbound webhooks. Returns the created integration including its webhook URL and HMAC secret for signature verification.
class CustomVCSIntegration extends pulumi.CustomResource {
  /// URL prefix for repositories covered by this integration
  late final pulumi.Output<String> baseUrl;
  /// ISO 8601 timestamp of when the integration was created
  late final pulumi.Output<String> created;
  /// ESC environment reference in 'project/envName' format containing VCS credentials
  late final pulumi.Output<String> environment;
  /// Unique identifier (UUID) for this integration
  late final pulumi.Output<String> integrationId;
  /// ISO 8601 timestamp of when the integration was last modified
  late final pulumi.Output<String> modified;
  /// Human-readable name for the integration
  late final pulumi.Output<String> name;
  /// List of repositories configured on this integration
  late final pulumi.Output<List<Map<String, dynamic>>?> repositories;
  /// Version control system type
  late final pulumi.Output<String> vcsType;
  /// HMAC secret for webhook signature verification. Only returned on integration creation; subsequent GET requests omit this field.
  late final pulumi.Output<String?> webhookSecret;
  /// Full webhook endpoint URL that the external VCS should POST events to. This URL is generated by the service and includes the integration ID.
  late final pulumi.Output<String?> webhookUrl;

  /// Creates a new [CustomVCSIntegration].
  /// [name] The Pulumi resource name.
  /// [args] Arguments used to configure this [CustomVCSIntegration]. {@macro pulumi_api_integrations_custom_vcsintegration_args_doc}
  /// [options] Resource options controlling this resource's behavior.
  CustomVCSIntegration(
    String name, {
    CustomVCSIntegrationArgs? args,
    pulumi.CustomResourceOptions? options,
  }) : super(
          'pulumiservice:api/integrations:CustomVCSIntegration',
          name,
          pulumi.Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? pulumi.CustomResourceOptions(),
        ) {
    baseUrl = registerOutput<String>('baseUrl');
    created = registerOutput<String>('created');
    environment = registerOutput<String>('environment');
    integrationId = registerOutput<String>('integrationId');
    modified = registerOutput<String>('modified');
    this.name = registerOutput<String>('name');
    repositories = registerOutput<List<Map<String, dynamic>>?>('repositories');
    vcsType = registerOutput<String>('vcsType');
    webhookSecret = registerOutput<String?>('webhookSecret');
    webhookUrl = registerOutput<String?>('webhookUrl');
  }
}
