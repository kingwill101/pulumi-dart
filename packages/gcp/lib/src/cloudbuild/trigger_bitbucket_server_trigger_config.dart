// ignore_for_file: unused_element, unnecessary_cast

import 'trigger_bitbucket_server_trigger_config_pull_request.dart';
import 'trigger_bitbucket_server_trigger_config_push.dart';

class TriggerBitbucketServerTriggerConfig {
  /// The Bitbucket server config resource that this trigger config maps to.
  final String bitbucketServerConfigResource;

  /// Key of the project that the repo is in. For example: The key for https://mybitbucket.server/projects/TEST/repos/test-repo is "TEST".
  final String projectKey;

  /// Filter to match changes in pull requests.
  /// Structure is documented below.
  final TriggerBitbucketServerTriggerConfigPullRequest? pullRequest;

  /// Filter to match changes in refs like branches, tags.
  /// Structure is documented below.
  final TriggerBitbucketServerTriggerConfigPush? push;

  /// Slug of the repository. A repository slug is a URL-friendly version of a repository name, automatically generated by Bitbucket for use in the URL.
  /// For example, if the repository name is 'test repo', in the URL it would become 'test-repo' as in https://mybitbucket.server/projects/TEST/repos/test-repo.
  final String repoSlug;

  /// Creates a new [TriggerBitbucketServerTriggerConfig].
  /// [bitbucketServerConfigResource] The Bitbucket server config resource that this trigger config maps to.
  /// [projectKey] Key of the project that the repo is in. For example: The key for https://mybitbucket.server/projects/TEST/repos/test-repo is "TEST".
  /// [pullRequest] Filter to match changes in pull requests.
  /// [push] Filter to match changes in refs like branches, tags.
  /// [repoSlug] Slug of the repository. A repository slug is a URL-friendly version of a repository name, automatically generated by Bitbucket for use in the URL.
  TriggerBitbucketServerTriggerConfig({
    required this.bitbucketServerConfigResource,
    required this.projectKey,
    this.pullRequest,
    this.push,
    required this.repoSlug,
  });

  Map<String, dynamic> toMap() {
    final map = <String, dynamic>{};
    map['bitbucketServerConfigResource'] = bitbucketServerConfigResource;
    map['projectKey'] = projectKey;
    final pullRequestValue = pullRequest;
    if (pullRequestValue != null) {
      map['pullRequest'] = pullRequestValue.toMap();
    }
    final pushValue = push;
    if (pushValue != null) {
      map['push'] = pushValue.toMap();
    }
    map['repoSlug'] = repoSlug;
    return map;
  }

  factory TriggerBitbucketServerTriggerConfig.fromMap(
      Map<String, dynamic> map) {
    return TriggerBitbucketServerTriggerConfig(
      bitbucketServerConfigResource:
          map['bitbucketServerConfigResource'] as String,
      projectKey: map['projectKey'] as String,
      pullRequest: map['pullRequest'] == null
          ? null
          : TriggerBitbucketServerTriggerConfigPullRequest.fromMap(
              (map['pullRequest'] as Map).cast<String, dynamic>()),
      push: map['push'] == null
          ? null
          : TriggerBitbucketServerTriggerConfigPush.fromMap(
              (map['push'] as Map).cast<String, dynamic>()),
      repoSlug: map['repoSlug'] as String,
    );
  }
}
