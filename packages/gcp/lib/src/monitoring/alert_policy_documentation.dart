// ignore_for_file: unused_element, unnecessary_cast

import 'package:pulumi/pulumi.dart' as pulumi;
import 'alert_policy_documentation_link.dart';

class AlertPolicyDocumentation {
  /// The text of the documentation, interpreted according to mimeType.
  /// The content may not exceed 8,192 Unicode characters and may not
  /// exceed more than 10,240 bytes when encoded in UTF-8 format,
  /// whichever is smaller.
  final String? content;

  /// Links to content such as playbooks, repositories, and other resources. This field can contain up to 3 entries.
  /// Structure is documented below.
  final List<AlertPolicyDocumentationLink>? links;

  /// The format of the content field. Presently, only the value
  /// "text/markdown" is supported.
  final String? mimeType;

  /// The subject line of the notification. The subject line may not
  /// exceed 10,240 bytes. In notifications generated by this policy the contents
  /// of the subject line after variable expansion will be truncated to 255 bytes
  /// or shorter at the latest UTF-8 character boundary.
  final String? subject;

  /// Creates a new [AlertPolicyDocumentation].
  /// [content] The text of the documentation, interpreted according to mimeType.
  /// [links] Links to content such as playbooks, repositories, and other resources. This field can contain up to 3 entries.
  /// [mimeType] The format of the content field. Presently, only the value
  /// [subject] The subject line of the notification. The subject line may not
  AlertPolicyDocumentation({
    this.content,
    this.links,
    this.mimeType,
    this.subject,
  });

  Map<String, dynamic> toMap() {
    return <String, dynamic>{
      'content': ?content,
      'links': ?links == null
          ? null
          : pulumi.Input.encodeList<
              AlertPolicyDocumentationLink,
              Map<String, dynamic>
            >(links!, (value) => value.toMap()),
      'mimeType': ?mimeType,
      'subject': ?subject,
    };
  }

  factory AlertPolicyDocumentation.fromMap(Map<String, dynamic> map) {
    return AlertPolicyDocumentation(
      content: map['content'] == null ? null : map['content'] as String,
      links: map['links'] == null
          ? null
          : pulumi.Input.decodeList<AlertPolicyDocumentationLink>(
              map['links'],
              (value) => AlertPolicyDocumentationLink.fromMap(
                (value as Map).cast<String, dynamic>(),
              ),
            ),
      mimeType: map['mimeType'] == null ? null : map['mimeType'] as String,
      subject: map['subject'] == null ? null : map['subject'] as String,
    );
  }
}
