import '../settings_application_settings_access_denied_page_settings/settings_application_settings_access_denied_page_settings.dart';
import '../settings_application_settings_attribute_propagation_settings/settings_application_settings_attribute_propagation_settings.dart';
import '../settings_application_settings_csm_settings/settings_application_settings_csm_settings.dart';

class SettingsApplicationSettings {
  /// Customization for Access Denied page. IAP allows customers to define a custom URI
  /// to use as the error page when access is denied to users. If IAP prevents access
  /// to this page, the default IAP error page will be displayed instead.
  /// Structure is documented below.
  final SettingsApplicationSettingsAccessDeniedPageSettings?
      accessDeniedPageSettings;

  /// Settings to configure attribute propagation.
  /// Structure is documented below.
  final SettingsApplicationSettingsAttributePropagationSettings?
      attributePropagationSettings;

  /// The Domain value to set for cookies generated by IAP. This value is not validated by the API,
  /// but will be ignored at runtime if invalid.
  final String? cookieDomain;

  /// Settings to configure IAP's behavior for a service mesh.
  /// Structure is documented below.
  final SettingsApplicationSettingsCsmSettings? csmSettings;

  SettingsApplicationSettings({
    this.accessDeniedPageSettings,
    this.attributePropagationSettings,
    this.cookieDomain,
    this.csmSettings,
  });

  Map<String, dynamic> toMap() {
    final map = <String, dynamic>{};
    final accessDeniedPageSettingsValue = accessDeniedPageSettings;
    if (accessDeniedPageSettingsValue != null) {
      map['accessDeniedPageSettings'] = accessDeniedPageSettingsValue.toMap();
    }
    final attributePropagationSettingsValue = attributePropagationSettings;
    if (attributePropagationSettingsValue != null) {
      map['attributePropagationSettings'] =
          attributePropagationSettingsValue.toMap();
    }
    final cookieDomainValue = cookieDomain;
    if (cookieDomainValue != null) {
      map['cookieDomain'] = cookieDomainValue;
    }
    final csmSettingsValue = csmSettings;
    if (csmSettingsValue != null) {
      map['csmSettings'] = csmSettingsValue.toMap();
    }
    return map;
  }

  factory SettingsApplicationSettings.fromMap(Map<String, dynamic> map) {
    return SettingsApplicationSettings(
      accessDeniedPageSettings: map['accessDeniedPageSettings'] == null
          ? null
          : SettingsApplicationSettingsAccessDeniedPageSettings.fromMap(
              (map['accessDeniedPageSettings'] as Map).cast<String, dynamic>()),
      attributePropagationSettings: map['attributePropagationSettings'] == null
          ? null
          : SettingsApplicationSettingsAttributePropagationSettings.fromMap(
              (map['attributePropagationSettings'] as Map)
                  .cast<String, dynamic>()),
      cookieDomain:
          map['cookieDomain'] == null ? null : map['cookieDomain'] as String,
      csmSettings: map['csmSettings'] == null
          ? null
          : SettingsApplicationSettingsCsmSettings.fromMap(
              (map['csmSettings'] as Map).cast<String, dynamic>()),
    );
  }
}
