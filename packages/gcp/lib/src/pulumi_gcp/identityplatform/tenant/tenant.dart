class Tenant extends CustomResource {
  /// Whether to allow email/password user authentication.
  late final Output<bool?> allowPasswordSignup;

  /// Options related to how clients making requests on behalf of a tenant should be configured.
  /// Structure is documented below.
  late final Output<TenantClient?> client;

  /// Whether authentication is disabled for the tenant. If true, the users under
  /// the disabled tenant are not allowed to sign-in. Admins of the disabled tenant
  /// are not able to manage its users.
  late final Output<bool?> disableAuth;

  /// Human friendly display name of the tenant.
  late final Output<String> displayName;

  /// Whether to enable email link user authentication.
  late final Output<bool?> enableEmailLinkSignin;

  /// The name of the tenant that is generated by the server
  late final Output<String> name;

  /// The ID of the project in which the resource belongs.
  /// If it is not provided, the provider project is used.
  late final Output<String> project;

  Tenant(
    String name, {
    TenantArgs? args,
    CustomResourceOptions? options,
  }) : super(
          'gcp:identityplatform/tenant:Tenant',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.allowPasswordSignup = registerOutput<bool?>('allowPasswordSignup');
    this.client = registerOutput<TenantClient?>('client');
    this.disableAuth = registerOutput<bool?>('disableAuth');
    this.displayName = registerOutput<String>('displayName');
    this.enableEmailLinkSignin = registerOutput<bool?>('enableEmailLinkSignin');
    this.name = registerOutput<String>('name');
    this.project = registerOutput<String>('project');
  }
}
