class IAMPolicyServiceaccountIAmpolicy extends pulumi.CustomResource {
  /// (Computed) The etag of the service account IAM policy.
  late final pulumi.Output<String> etag;

  /// The policy data generated by
  /// a `gcp.organizations.getIAMPolicy` data source.
  late final pulumi.Output<String> policyData;

  /// The fully-qualified name of the service account to apply policy to.
  late final pulumi.Output<String> serviceAccountId;

  IAMPolicyServiceaccountIAmpolicy(
    String name, {
    IAMPolicyServiceaccountIAmpolicyArgs? args,
    pulumi.CustomResourceOptions? options,
  }) : super(
          'gcp:serviceaccount/iAMPolicy:IAMPolicy',
          name,
          pulumi.Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? pulumi.CustomResourceOptions(),
        ) {
    this.etag = registerOutput<String>('etag');
    this.policyData = registerOutput<String>('policyData');
    this.serviceAccountId = registerOutput<String>('serviceAccountId');
  }
}
