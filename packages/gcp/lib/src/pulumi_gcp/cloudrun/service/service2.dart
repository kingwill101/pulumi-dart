/// ## Import
///
/// Service can be imported using any of these accepted formats:
///
/// * `locations/{{location}}/namespaces/{{project}}/services/{{name}}`
///
/// * `{{location}}/{{project}}/{{name}}`
///
/// * `{{location}}/{{name}}`
///
/// When using the `pulumi import` command, Service can be imported using one of the formats above. For example:
///
/// ```sh
/// $ pulumi import gcp:cloudrun/service:Service default locations/{{location}}/namespaces/{{project}}/services/{{name}}
/// ```
///
/// ```sh
/// $ pulumi import gcp:cloudrun/service:Service default {{location}}/{{project}}/{{name}}
/// ```
///
/// ```sh
/// $ pulumi import gcp:cloudrun/service:Service default {{location}}/{{name}}
/// ```
class Service2 extends CustomResource {
  /// If set to `true`, the revision name (template.metadata.name) will be omitted and
  /// autogenerated by Cloud Run. This cannot be set to `true` while `template.metadata.name`
  /// is also set.
  /// (For legacy support, if `template.metadata.name` is unset in state while
  /// this field is set to false, the revision name will still autogenerate.)
  late final Output<bool?> autogenerateRevisionName;

  /// The location of the cloud run instance. eg us-central1
  late final Output<String> location;

  /// Metadata associated with this Service, including name, namespace, labels,
  /// and annotations.
  /// Structure is documented below.
  late final Output<ServiceMetadata> metadata;

  /// Name must be unique within a Google Cloud project and region.
  /// Is required when creating resources. Name is primarily intended
  /// for creation idempotence and configuration definition. Cannot be updated.
  /// More info: https://kubernetes.io/docs/concepts/overview/working-with-objects/names/#names
  late final Output<String> name;

  /// The ID of the project in which the resource belongs.
  /// If it is not provided, the provider project is used.
  late final Output<String> project;

  /// (Output)
  /// Status of the condition, one of True, False, Unknown.
  late final Output<List<ServiceStatus>> statuses;

  /// template holds the latest specification for the Revision to
  /// be stamped out. The template references the container image, and may also
  /// include labels and annotations that should be attached to the Revision.
  /// To correlate a Revision, and/or to force a Revision to be created when the
  /// spec doesn't otherwise change, a nonce label may be provided in the
  /// template metadata. For more details, see:
  /// https://github.com/knative/serving/blob/main/docs/client-conventions.md#associate-modifications-with-revisions
  /// Cloud Run does not currently support referencing a build that is
  /// responsible for materializing the container image from source.
  /// Structure is documented below.
  late final Output<ServiceTemplate?> template;

  /// Traffic specifies how to distribute traffic over a collection of Knative Revisions
  /// and Configurations
  /// Structure is documented below.
  late final Output<List<ServiceTraffic>> traffics;

  Service2(
    String name, {
    ServiceArgs2? args,
    CustomResourceOptions? options,
  }) : super(
          'gcp:cloudrun/service:Service',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.autogenerateRevisionName =
        registerOutput<bool?>('autogenerateRevisionName');
    this.location = registerOutput<String>('location');
    this.metadata = registerOutput<ServiceMetadata>('metadata');
    this.name = registerOutput<String>('name');
    this.project = registerOutput<String>('project');
    this.statuses = registerOutput<List<ServiceStatus>>('statuses');
    this.template = registerOutput<ServiceTemplate?>('template');
    this.traffics = registerOutput<List<ServiceTraffic>>('traffics');
  }
}
