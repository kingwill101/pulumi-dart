import 'package:pulumi/pulumi.dart';
import '../signing_profile_revocation_record/signing_profile_revocation_record.dart';
import '../signing_profile_signature_validity_period/signing_profile_signature_validity_period.dart';
import '../signing_profile_signing_material/signing_profile_signing_material.dart';
import 'signing_profile_args.dart';

/// Creates a Signer Signing Profile. A signing profile contains information about the code signing configuration parameters that can be used by a given code signing user.
///
/// ## Example Usage
///
///
///
/// ## Import
///
/// Using `pulumi import`, import Signer signing profiles using the `name`. For example:
///
/// ```sh
/// $ pulumi import aws:signer/signingProfile:SigningProfile test_signer_signing_profile test_sp_DdW3Mk1foYL88fajut4mTVFGpuwfd4ACO6ANL0D1uIj7lrn8adK
/// ```
class SigningProfile extends CustomResource {
  /// The Amazon Resource Name (ARN) for the signing profile.
  late final Output<String> arn;

  /// A unique signing profile name. By default generated by Terraform. Signing profile names are immutable and cannot be reused after canceled.
  late final Output<String> name;

  /// A signing profile name prefix. Terraform will generate a unique suffix. Conflicts with `name`.
  late final Output<String> namePrefix;

  /// A human-readable name for the signing platform associated with the signing profile.
  late final Output<String> platformDisplayName;

  /// The ID of the platform that is used by the target signing profile.
  late final Output<String> platformId;

  /// Region where this resource will be [managed](https://docs.aws.amazon.com/general/latest/gr/rande.html#regional-endpoints). Defaults to the Region set in the provider configuration.
  late final Output<String> region;

  /// Revocation information for a signing profile. See `revocation_record` Block below for details.
  late final Output<List<SigningProfileRevocationRecord>> revocationRecords;

  /// The validity period for a signing job. See `signature_validity_period` Block below for details.
  late final Output<SigningProfileSignatureValidityPeriod>
      signatureValidityPeriod;

  /// The AWS Certificate Manager certificate that will be used to sign code with the new signing profile. See `signing_material` Block below for details.
  late final Output<SigningProfileSigningMaterial> signingMaterial;

  /// Map of key-value pairs for signing. These can include any information that you want to use during signing.
  late final Output<Map<String, String>?> signingParameters;

  /// The status of the target signing profile.
  late final Output<String> status;

  /// A list of tags associated with the signing profile. If configured with a provider `default_tags` configuration block present, tags with matching keys will overwrite those defined at the provider-level.
  late final Output<Map<String, String>?> tags;

  /// A map of tags assigned to the resource, including those inherited from the provider `default_tags` configuration block.
  late final Output<Map<String, String>> tagsAll;

  /// The current version of the signing profile.
  late final Output<String> version;

  /// The signing profile ARN, including the profile version.
  late final Output<String> versionArn;

  SigningProfile(
    String name, {
    SigningProfileArgs? args,
    CustomResourceOptions? options,
  }) : super(
          'aws:signer/signingProfile:SigningProfile',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.arn = registerOutput<String>('arn');
    this.name = registerOutput<String>('name');
    this.namePrefix = registerOutput<String>('namePrefix');
    this.platformDisplayName = registerOutput<String>('platformDisplayName');
    this.platformId = registerOutput<String>('platformId');
    this.region = registerOutput<String>('region');
    this.revocationRecords =
        registerOutput<List<SigningProfileRevocationRecord>>(
            'revocationRecords');
    this.signatureValidityPeriod =
        registerOutput<SigningProfileSignatureValidityPeriod>(
            'signatureValidityPeriod');
    this.signingMaterial =
        registerOutput<SigningProfileSigningMaterial>('signingMaterial');
    this.signingParameters =
        registerOutput<Map<String, String>?>('signingParameters');
    this.status = registerOutput<String>('status');
    this.tags = registerOutput<Map<String, String>?>('tags');
    this.tagsAll = registerOutput<Map<String, String>>('tagsAll');
    this.version = registerOutput<String>('version');
    this.versionArn = registerOutput<String>('versionArn');
  }
}
