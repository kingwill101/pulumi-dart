/// Provides a AWS Transfer Server resource.
///
/// > **NOTE on AWS IAM permissions:** If the `endpoint_type` is set to `VPC`, the `ec2:DescribeVpcEndpoints` and `ec2:ModifyVpcEndpoint` [actions](https://docs.aws.amazon.com/service-authorization/latest/reference/list_amazonec2.html#amazonec2-actions-as-permissions) are used.
///
/// > **NOTE:** Use the `aws.transfer.Tag` resource to manage the system tags used for [custom hostnames](https://docs.aws.amazon.com/transfer/latest/userguide/requirements-dns.html#tag-custom-hostname-cdk).
///
/// ## Example Usage
///
/// ### Basic
///
///
///
/// ### Security Policy Name
///
///
///
/// ### VPC Endpoint
///
///
///
/// ### AWS Directory authentication
///
///
///
/// ### AWS Lambda authentication
///
///
///
/// ### Protocols
///
///
///
/// ### Using Structured Logging Destinations
///
///
///
/// ## Import
///
/// In Terraform v1.5.0 and later, use an `import` Block to import Transfer Servers using the server `id`. For example:
///
///
/// Using `pulumi import`, import Transfer Servers using the server `id`. For example:
///
/// ```sh
/// $ pulumi import aws:transfer/server:Server example s-12345678
/// ```
///
/// Certain resource arguments, such as `host_key`, cannot be read via the API and imported into the provider. This provider will display a difference for these arguments the first run after import if declared in the provider configuration for an imported resource.
class Server extends CustomResource {
  /// Amazon Resource Name (ARN) of Transfer Server
  late final Output<String> arn;

  /// The Amazon Resource Name (ARN) of the AWS Certificate Manager (ACM) certificate. This is required when `protocols` is set to `FTPS`
  late final Output<String?> certificate;

  /// The directory service ID of the directory service you want to connect to with an `identity_provider_type` of `AWS_DIRECTORY_SERVICE`.
  late final Output<String?> directoryId;

  /// The domain of the storage system that is used for file transfers. Valid values are: `S3` and `EFS`. The default value is `S3`.
  late final Output<String?> domain;

  /// The endpoint of the Transfer Server (e.g., `s-12345678.server.transfer.REGION.amazonaws.com`)
  late final Output<String> endpoint;

  /// The virtual private cloud (VPC) endpoint settings that you want to configure for your SFTP server. See `endpoint_details` Block below for details.
  late final Output<ServerEndpointDetails?> endpointDetails;

  /// The type of endpoint that you want your SFTP server connect to. If you connect to a `VPC` (or `VPC_ENDPOINT`), your SFTP server isn't accessible over the public internet. If you want to connect your SFTP server via public internet, set `PUBLIC`.  Defaults to `PUBLIC`.
  late final Output<String?> endpointType;

  /// A boolean that indicates all users associated with the server should be deleted so that the Server can be destroyed without error. The default value is `false`. This option only applies to servers configured with a `SERVICE_MANAGED` `identity_provider_type`.
  late final Output<bool?> forceDestroy;

  /// The ARN for a lambda function to use for the Identity provider with an `identity_provider_type` of `AWS_LAMBDA`.
  late final Output<String?> function;

  /// RSA, ECDSA, or ED25519 private key (e.g., as generated by the `ssh-keygen -t rsa -b 2048 -N "" -m PEM -f my-new-server-key`, `ssh-keygen -t ecdsa -b 256 -N "" -m PEM -f my-new-server-key` or `ssh-keygen -t ed25519 -N "" -f my-new-server-key` commands).
  late final Output<String?> hostKey;

  /// This value contains the message-digest algorithm (MD5) hash of the server's host key. This value is equivalent to the output of the `ssh-keygen -l -E md5 -f my-new-server-key` command.
  late final Output<String> hostKeyFingerprint;

  /// The mode of authentication enabled for this service. The default value is `SERVICE_MANAGED`, which allows you to store and access SFTP user credentials within the service. `API_GATEWAY` indicates that user authentication requires a call to an API Gateway endpoint URL provided by you to integrate an identity provider of your choice. Using `AWS_DIRECTORY_SERVICE` will allow for authentication against AWS Managed Active Directory or Microsoft Active Directory in your on-premises environment, or in AWS using AD Connectors. Use the `AWS_LAMBDA` value to directly use a Lambda function as your identity provider. If you choose this value, you must specify the ARN for the lambda function in the `function` argument.
  late final Output<String?> identityProviderType;

  /// Amazon Resource Name (ARN) of the IAM role used to authenticate the user account with an `identity_provider_type` of `API_GATEWAY`.
  late final Output<String?> invocationRole;

  /// Amazon Resource Name (ARN) of an IAM role that allows the service to write your SFTP users’ activity to your Amazon CloudWatch logs for monitoring and auditing purposes.
  late final Output<String?> loggingRole;

  /// Specify a string to display when users connect to a server. This string is displayed after the user authenticates. The SFTP protocol does not support post-authentication display banners.
  late final Output<String?> postAuthenticationLoginBanner;

  /// Specify a string to display when users connect to a server. This string is displayed before the user authenticates.
  late final Output<String?> preAuthenticationLoginBanner;

  /// The protocol settings that are configured for your server. See `protocol_details` Block below for details.
  late final Output<ServerProtocolDetails> protocolDetails;

  /// Specifies the file transfer protocol or protocols over which your file transfer protocol client can connect to your server's endpoint. This defaults to `SFTP` . The available protocols are:
  /// * `AS2`: File transfer over Applicability Statement 2
  /// * `SFTP`: File transfer over SSH
  /// * `FTPS`: File transfer with TLS encryption
  /// * `FTP`: Unencrypted file transfer
  late final Output<List<String>> protocols;

  /// Region where this resource will be [managed](https://docs.aws.amazon.com/general/latest/gr/rande.html#regional-endpoints). Defaults to the Region set in the provider configuration.
  late final Output<String> region;

  /// Specifies whether or not performance for your Amazon S3 directories is optimized. This is disabled by default. See `s3_storage_options` Block below for details.
  late final Output<ServerS3StorageOptions> s3StorageOptions;

  /// Specifies the name of the security policy that is attached to the server. Default value is: `TransferSecurityPolicy-2018-11`. The available values are:
  /// * `TransferSecurityPolicy-2018-11`
  /// * `TransferSecurityPolicy-2020-06`
  /// * `TransferSecurityPolicy-2022-03`
  /// * `TransferSecurityPolicy-2023-05`
  /// * `TransferSecurityPolicy-2024-01`
  /// * `TransferSecurityPolicy-2025-03`
  /// * `TransferSecurityPolicy-FIPS-2020-06`
  /// * `TransferSecurityPolicy-FIPS-2023-05`
  /// * `TransferSecurityPolicy-FIPS-2024-01`
  /// * `TransferSecurityPolicy-FIPS-2024-05`
  /// * `TransferSecurityPolicy-FIPS-2025-03`
  /// * `TransferSecurityPolicy-PQ-SSH-Experimental-2023-04`
  /// * `TransferSecurityPolicy-PQ-SSH-FIPS-Experimental-2023-04`
  /// * `TransferSecurityPolicy-Restricted-2018-11`
  /// * `TransferSecurityPolicy-Restricted-2020-06`
  /// * `TransferSecurityPolicy-Restricted-2024-06`
  /// * `TransferSecurityPolicy-SshAuditCompliant-2025-02`
  /// * `TransferSecurityPolicy-AS2Restricted-2025-07`
  ///
  /// See [Security policies for AWS Transfer Family servers](https://docs.aws.amazon.com/transfer/latest/userguide/security-policies.html) for details.
  late final Output<String?> securityPolicyName;

  /// For SFTP-enabled servers with an `identity_provider_type` of `API_GATEWAY` or `AWS_LAMBDA`. Valid values are `PASSWORD`, `PUBLIC_KEY`, `PUBLIC_KEY_OR_PASSWORD` and `PUBLIC_KEY_AND_PASSWORD`. Default value is: `PUBLIC_KEY_OR_PASSWORD`.
  late final Output<String> sftpAuthenticationMethods;

  /// A set of ARNs of destinations that will receive structured logs from the transfer server such as CloudWatch Log Group ARNs. If provided this enables the transfer server to emit structured logs to the specified locations.
  late final Output<List<String>?> structuredLogDestinations;

  /// A map of tags to assign to the resource. If configured with a provider `default_tags` configuration block present, tags with matching keys will overwrite those defined at the provider-level.
  late final Output<Map<String, String>?> tags;

  /// A map of tags assigned to the resource, including those inherited from the provider `default_tags` configuration block.
  late final Output<Map<String, String>> tagsAll;

  /// URL of the service endpoint used to authenticate users with an `identity_provider_type` of `API_GATEWAY`.
  late final Output<String?> url;

  /// Specifies the workflow details. See `workflow_details` Block below for details.
  late final Output<ServerWorkflowDetails?> workflowDetails;

  Server(
    String name, {
    ServerArgs? args,
    CustomResourceOptions? options,
  }) : super(
          'aws:transfer/server:Server',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.arn = registerOutput<String>('arn');
    this.certificate = registerOutput<String?>('certificate');
    this.directoryId = registerOutput<String?>('directoryId');
    this.domain = registerOutput<String?>('domain');
    this.endpoint = registerOutput<String>('endpoint');
    this.endpointDetails =
        registerOutput<ServerEndpointDetails?>('endpointDetails');
    this.endpointType = registerOutput<String?>('endpointType');
    this.forceDestroy = registerOutput<bool?>('forceDestroy');
    this.function = registerOutput<String?>('function');
    this.hostKey = registerOutput<String?>('hostKey');
    this.hostKeyFingerprint = registerOutput<String>('hostKeyFingerprint');
    this.identityProviderType = registerOutput<String?>('identityProviderType');
    this.invocationRole = registerOutput<String?>('invocationRole');
    this.loggingRole = registerOutput<String?>('loggingRole');
    this.postAuthenticationLoginBanner =
        registerOutput<String?>('postAuthenticationLoginBanner');
    this.preAuthenticationLoginBanner =
        registerOutput<String?>('preAuthenticationLoginBanner');
    this.protocolDetails =
        registerOutput<ServerProtocolDetails>('protocolDetails');
    this.protocols = registerOutput<List<String>>('protocols');
    this.region = registerOutput<String>('region');
    this.s3StorageOptions =
        registerOutput<ServerS3StorageOptions>('s3StorageOptions');
    this.securityPolicyName = registerOutput<String?>('securityPolicyName');
    this.sftpAuthenticationMethods =
        registerOutput<String>('sftpAuthenticationMethods');
    this.structuredLogDestinations =
        registerOutput<List<String>?>('structuredLogDestinations');
    this.tags = registerOutput<Map<String, String>?>('tags');
    this.tagsAll = registerOutput<Map<String, String>>('tagsAll');
    this.url = registerOutput<String?>('url');
    this.workflowDetails =
        registerOutput<ServerWorkflowDetails?>('workflowDetails');
  }
}
