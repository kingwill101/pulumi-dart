import 'package:pulumi/pulumi.dart' as pulumi;
import '../load_balancer_access_logs/load_balancer_access_logs_elb.dart';
import '../load_balancer_health_check/load_balancer_health_check.dart';
import '../load_balancer_listener/load_balancer_listener.dart';
import 'load_balancer_elb_args.dart';

/// Provides an Elastic Load Balancer resource, also known as a "Classic
/// Load Balancer" after the release of
/// Application/Network Load Balancers.
///
/// > **NOTE on ELB Instances and ELB Attachments:** This provider currently
/// provides both a standalone ELB Attachment resource
/// (describing an instance attached to an ELB), and an ELB resource with
/// `instances` defined in-line. At this time you cannot use an ELB with in-line
/// instances in conjunction with a ELB Attachment resources. Doing so will cause a
/// conflict and will overwrite attachments.
///
/// ## Example Usage
///
///
///
/// ## Note on ECDSA Key Algorithm
///
/// If the ARN of the `ssl_certificate_id` that is pointed to references a
/// certificate that was signed by an ECDSA key, note that ELB only supports the
/// P256 and P384 curves.  Using a certificate signed by a key using a different
/// curve could produce the error `ERR_SSL_VERSION_OR_CIPHER_MISMATCH` in your
/// browser.
///
/// ## Import
///
/// Using `pulumi import`, import ELBs using the `name`. For example:
///
/// ```sh
/// $ pulumi import aws:elb/loadBalancer:LoadBalancer bar elb-production-12345
/// ```
class LoadBalancerElb extends pulumi.CustomResource {
  /// An Access Logs block. Access Logs documented below.
  late final pulumi.Output<LoadBalancerAccessLogsElb?> accessLogs;

  /// The ARN of the ELB
  late final pulumi.Output<String> arn;

  /// The AZ's to serve traffic in.
  late final pulumi.Output<List<String>> availabilityZones;

  /// Boolean to enable connection draining. Default: `false`
  late final pulumi.Output<bool?> connectionDraining;

  /// The time in seconds to allow for connections to drain. Default: `300`
  late final pulumi.Output<int?> connectionDrainingTimeout;

  /// Enable cross-zone load balancing. Default: `true`
  late final pulumi.Output<bool?> crossZoneLoadBalancing;

  /// Determines how the load balancer handles requests that might pose a security risk to an application due to HTTP desync. Valid values are `monitor`, `defensive` (default), `strictest`.
  late final pulumi.Output<String?> desyncMitigationMode;

  /// The DNS name of the ELB
  late final pulumi.Output<String> dnsName;

  /// A health_check block. Health Check documented below.
  late final pulumi.Output<LoadBalancerHealthCheck> healthCheck;

  /// The time in seconds that the connection is allowed to be idle. Default: `60`
  late final pulumi.Output<int?> idleTimeout;

  /// A list of instance ids to place in the ELB pool.
  late final pulumi.Output<List<String>> instances;

  /// If true, ELB will be an internal ELB.
  late final pulumi.Output<bool> internal;

  /// A list of listener blocks. Listeners documented below.
  late final pulumi.Output<List<LoadBalancerListener>> listeners;

  /// The name of the ELB. By default generated by this provider.
  late final pulumi.Output<String> name;

  /// Creates a unique name beginning with the specified
  /// prefix. Conflicts with `name`.
  late final pulumi.Output<String> namePrefix;

  /// Region where this resource will be [managed](https://docs.aws.amazon.com/general/latest/gr/rande.html#regional-endpoints). Defaults to the Region set in the provider configuration.
  late final pulumi.Output<String> region;

  /// A list of security group IDs to assign to the ELB.
  /// Only valid if creating an ELB within a VPC
  late final pulumi.Output<List<String>> securityGroups;

  /// The name of the security group that you can use as
  /// part of your inbound rules for your load balancer's back-end application
  /// instances. Use this for Classic or Default VPC only.
  late final pulumi.Output<String> sourceSecurityGroup;

  /// The ID of the security group that you can use as
  /// part of your inbound rules for your load balancer's back-end application
  /// instances. Only available on ELBs launched in a VPC.
  late final pulumi.Output<String> sourceSecurityGroupId;

  /// A list of subnet IDs to attach to the ELB. When an update to subnets will remove all current subnets, this will force a new resource.
  late final pulumi.Output<List<String>> subnets;

  /// A map of tags to assign to the resource. If configured with a provider `default_tags` configuration block present, tags with matching keys will overwrite those defined at the provider-level.
  ///
  /// Exactly one of `availability_zones` or `subnets` must be specified: this
  /// determines if the ELB exists in a VPC or in EC2-classic.
  late final pulumi.Output<Map<String, String>?> tags;

  /// A map of tags assigned to the resource, including those inherited from the provider `default_tags` configuration block.
  late final pulumi.Output<Map<String, String>> tagsAll;

  /// The canonical hosted zone ID of the ELB (to be used in a Route 53 Alias record)
  late final pulumi.Output<String> zoneId;

  LoadBalancerElb(
    String name, {
    LoadBalancerElbArgs? args,
    pulumi.CustomResourceOptions? options,
  }) : super(
          'aws:elb/loadBalancer:LoadBalancer',
          name,
          pulumi.Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? pulumi.CustomResourceOptions(),
        ) {
    this.accessLogs = registerOutput<LoadBalancerAccessLogsElb?>('accessLogs');
    this.arn = registerOutput<String>('arn');
    this.availabilityZones = registerOutput<List<String>>('availabilityZones');
    this.connectionDraining = registerOutput<bool?>('connectionDraining');
    this.connectionDrainingTimeout =
        registerOutput<int?>('connectionDrainingTimeout');
    this.crossZoneLoadBalancing =
        registerOutput<bool?>('crossZoneLoadBalancing');
    this.desyncMitigationMode = registerOutput<String?>('desyncMitigationMode');
    this.dnsName = registerOutput<String>('dnsName');
    this.healthCheck = registerOutput<LoadBalancerHealthCheck>('healthCheck');
    this.idleTimeout = registerOutput<int?>('idleTimeout');
    this.instances = registerOutput<List<String>>('instances');
    this.internal = registerOutput<bool>('internal');
    this.listeners = registerOutput<List<LoadBalancerListener>>('listeners');
    this.name = registerOutput<String>('name');
    this.namePrefix = registerOutput<String>('namePrefix');
    this.region = registerOutput<String>('region');
    this.securityGroups = registerOutput<List<String>>('securityGroups');
    this.sourceSecurityGroup = registerOutput<String>('sourceSecurityGroup');
    this.sourceSecurityGroupId =
        registerOutput<String>('sourceSecurityGroupId');
    this.subnets = registerOutput<List<String>>('subnets');
    this.tags = registerOutput<Map<String, String>?>('tags');
    this.tagsAll = registerOutput<Map<String, String>>('tagsAll');
    this.zoneId = registerOutput<String>('zoneId');
  }
}
