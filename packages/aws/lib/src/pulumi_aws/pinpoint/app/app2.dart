import 'package:pulumi/pulumi.dart';
import '../app_campaign_hook/app_campaign_hook.dart';
import '../app_limits/app_limits.dart';
import '../app_quiet_time/app_quiet_time.dart';
import 'app_args2.dart';

/// Provides a Pinpoint App resource.
///
/// ## Example Usage
///
///
///
/// ## Import
///
/// Using `pulumi import`, import Pinpoint App using the `application-id`. For example:
///
/// ```sh
/// $ pulumi import aws:pinpoint/app:App name application-id
/// ```
class App2 extends CustomResource {
  /// The Application ID of the Pinpoint App.
  late final Output<String> applicationId;

  /// Amazon Resource Name (ARN) of the PinPoint Application
  late final Output<String> arn;

  /// Specifies settings for invoking an AWS Lambda function that customizes a segment for a campaign
  late final Output<AppCampaignHook?> campaignHook;

  /// The default campaign limits for the app. These limits apply to each campaign for the app, unless the campaign overrides the default with limits of its own
  late final Output<AppLimits?> limits;

  /// The application name. By default generated by Pulumi
  late final Output<String> name;

  /// The name of the Pinpoint application. Conflicts with `name`
  late final Output<String> namePrefix;

  /// The default quiet time for the app. Each campaign for this app sends no messages during this time unless the campaign overrides the default with a quiet time of its own
  late final Output<AppQuietTime?> quietTime;

  /// Region where this resource will be [managed](https://docs.aws.amazon.com/general/latest/gr/rande.html#regional-endpoints). Defaults to the Region set in the provider configuration.
  late final Output<String> region;

  /// Key-value map of resource tags. If configured with a provider `default_tags` configuration block present, tags with matching keys will overwrite those defined at the provider-level.
  late final Output<Map<String, String>?> tags;

  /// A map of tags assigned to the resource, including those inherited from the provider `default_tags` configuration block.
  late final Output<Map<String, String>> tagsAll;

  App2(
    String name, {
    AppArgs2? args,
    CustomResourceOptions? options,
  }) : super(
          'aws:pinpoint/app:App',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.applicationId = registerOutput<String>('applicationId');
    this.arn = registerOutput<String>('arn');
    this.campaignHook = registerOutput<AppCampaignHook?>('campaignHook');
    this.limits = registerOutput<AppLimits?>('limits');
    this.name = registerOutput<String>('name');
    this.namePrefix = registerOutput<String>('namePrefix');
    this.quietTime = registerOutput<AppQuietTime?>('quietTime');
    this.region = registerOutput<String>('region');
    this.tags = registerOutput<Map<String, String>?>('tags');
    this.tagsAll = registerOutput<Map<String, String>>('tagsAll');
  }
}
