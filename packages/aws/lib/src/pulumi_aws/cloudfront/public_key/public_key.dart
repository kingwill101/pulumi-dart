class PublicKey extends CustomResource {
  /// Internal value used by CloudFront to allow future updates to the public key configuration.
  late final Output<String> callerReference;

  /// An optional comment about the public key.
  late final Output<String?> comment;

  /// The encoded public key that you want to add to CloudFront to use with features like field-level encryption.
  late final Output<String> encodedKey;

  /// The current version of the public key. For example: `E2QWRUHAPOMQZL`.
  late final Output<String> etag;

  /// The name for the public key. By default generated by this provider. Note: Do not set if using the key's id in another resource (e.g. KeyGroup) since it will result in a dependency error from AWS. Instead, it is recommended to use Pulumi autonaming by leaving this property unset (default behavior) or set the `namePrefix` property to allow the provider to autoname the resource.
  late final Output<String> name;

  /// The name for the public key. Conflicts with <span pulumi-lang-nodejs="`name`" pulumi-lang-dotnet="`Name`" pulumi-lang-go="`name`" pulumi-lang-python="`name`" pulumi-lang-yaml="`name`" pulumi-lang-java="`name`">`name`</span>.
  ///
  /// **NOTE:** When setting <span pulumi-lang-nodejs="`encodedKey`" pulumi-lang-dotnet="`EncodedKey`" pulumi-lang-go="`encodedKey`" pulumi-lang-python="`encoded_key`" pulumi-lang-yaml="`encodedKey`" pulumi-lang-java="`encodedKey`">`encoded_key`</span> value, there needs a newline at the end of string. Otherwise, multiple runs of pulumi will want to recreate the <span pulumi-lang-nodejs="`aws.cloudfront.PublicKey`" pulumi-lang-dotnet="`aws.cloudfront.PublicKey`" pulumi-lang-go="`cloudfront.PublicKey`" pulumi-lang-python="`cloudfront.PublicKey`" pulumi-lang-yaml="`aws.cloudfront.PublicKey`" pulumi-lang-java="`aws.cloudfront.PublicKey`">`aws.cloudfront.PublicKey`</span> resource.
  late final Output<String> namePrefix;

  PublicKey(
    String name, {
    PublicKeyArgs? args,
    CustomResourceOptions? options,
  }) : super(
          'aws:cloudfront/publicKey:PublicKey',
          name,
          Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? CustomResourceOptions(),
        ) {
    this.callerReference = registerOutput<String>('callerReference');
    this.comment = registerOutput<String?>('comment');
    this.encodedKey = registerOutput<String>('encodedKey');
    this.etag = registerOutput<String>('etag');
    this.name = registerOutput<String>('name');
    this.namePrefix = registerOutput<String>('namePrefix');
  }
}
