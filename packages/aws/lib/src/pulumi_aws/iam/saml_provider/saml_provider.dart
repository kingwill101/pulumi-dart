import 'package:pulumi/pulumi.dart' as pulumi;
import 'saml_provider_args.dart';

/// Provides an IAM SAML provider.
///
/// ## Example Usage
///
///
///
/// ## Import
///
/// ### Identity Schema
///
/// #### Required
///
/// - `arn` (String) Amazon Resource Name (ARN) of the IAM SAML provider.
///
///
/// Using `pulumi import`, import IAM SAML Providers using the `arn`. For example:
///
/// ```sh
/// $ pulumi import aws:iam/samlProvider:SamlProvider default arn:aws:iam::123456789012:saml-provider/SAMLADFS
/// ```
class SamlProvider extends pulumi.CustomResource {
  /// The ARN assigned by AWS for this provider.
  late final pulumi.Output<String> arn;

  /// The name of the provider to create.
  late final pulumi.Output<String> name;

  /// An XML document generated by an identity provider that supports SAML 2.0.
  late final pulumi.Output<String> samlMetadataDocument;

  /// Unique identifier assigned to the SAML provider.
  late final pulumi.Output<String> samlProviderUuid;

  /// Map of resource tags for the IAM SAML provider. .If configured with a provider `default_tags` configuration block present, tags with matching keys will overwrite those defined at the provider-level.
  late final pulumi.Output<Map<String, String>?> tags;

  /// A map of tags assigned to the resource, including those inherited from the provider `default_tags` configuration block.
  late final pulumi.Output<Map<String, String>> tagsAll;

  /// The expiration date and time for the SAML provider in RFC1123 format, e.g., `Mon, 02 Jan 2006 15:04:05 MST`.
  late final pulumi.Output<String> validUntil;

  SamlProvider(
    String name, {
    SamlProviderArgs? args,
    pulumi.CustomResourceOptions? options,
  }) : super(
          'aws:iam/samlProvider:SamlProvider',
          name,
          pulumi.Input.mapToInputs(args?.toMap() ?? const {}),
          options ?? pulumi.CustomResourceOptions(),
        ) {
    this.arn = registerOutput<String>('arn');
    this.name = registerOutput<String>('name');
    this.samlMetadataDocument = registerOutput<String>('samlMetadataDocument');
    this.samlProviderUuid = registerOutput<String>('samlProviderUuid');
    this.tags = registerOutput<Map<String, String>?>('tags');
    this.tagsAll = registerOutput<Map<String, String>>('tagsAll');
    this.validUntil = registerOutput<String>('validUntil');
  }
}
