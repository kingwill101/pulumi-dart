package codegen

import (
	"fmt"
	"path/filepath"
	"sort"
	"strings"
)

// normalizeGeneratedVersion trims a version string and removes a leading "v"
// prefix for pubspec compatibility.
func normalizeGeneratedVersion(version string) string {
	version = strings.TrimSpace(version)
	if version == "" {
		return ""
	}
	return strings.TrimPrefix(version, "v")
}

// generatedSDKPackageVersion computes the output SDK package version from the
// upstream provider version and version override env vars.
//
// Precedence:
// - PULUMI_DART_SDK_VERSION
// - normalized upstream version
// - fallback "0.0.1"
// Then appends PULUMI_DART_SDK_VERSION_SUFFIX when configured.
func generatedSDKPackageVersion(upstreamVersion, override, suffix string) string {
	if override = normalizeGeneratedVersion(override); override != "" {
		return override
	}

	baseVersion := normalizeGeneratedVersion(upstreamVersion)
	if baseVersion == "" {
		baseVersion = "0.0.1"
	}

	if suffix = strings.TrimSpace(suffix); suffix != "" {
		if strings.HasPrefix(suffix, "-") || strings.HasPrefix(suffix, "+") {
			return baseVersion + suffix
		}
		return baseVersion + "-" + suffix
	}

	return baseVersion
}

// dependencyPackageName reads a dependency pubspec name and falls back to a
// sanitized identifier when unavailable.
func dependencyPackageName(rootDirectory, dependencyPath, fallbackName string) string {
	pubspecPath := filepath.Join(rootDirectory, dependencyPath, "pubspec.yaml")
	pubspec, err := ReadAndParsePubspec(pubspecPath)
	if err != nil || pubspec == nil || pubspec.Name == "" {
		return sanitizeDartIdentifier(fallbackName)
	}
	return sanitizeDartIdentifier(pubspec.Name)
}

// generatedProgramStub returns a minimal Dart stack scaffold that annotates
// source provenance from the provided PCL source map.
func generatedProgramStub(pclSource map[string]string) []byte {
	var sourceFiles []string
	for filename := range pclSource {
		sourceFiles = append(sourceFiles, filename)
	}
	sort.Strings(sourceFiles)

	var sourceList string
	if len(sourceFiles) > 0 {
		sourceList = strings.Join(sourceFiles, ", ")
	} else {
		sourceList = "(no source files provided)"
	}

	return []byte(fmt.Sprintf(`import 'package:pulumi/pulumi.dart' as pulumi;

class GeneratedStack extends pulumi.Stack {
  GeneratedStack() {
    // Generated by pulumi-language-dart from PCL sources: %s
    // Replace this scaffold with generated resource definitions.
  }
}

Future<void> main() async {
  await pulumi.Deployment.runOrThrow(() => GeneratedStack());
}
`, sourceList))
}
